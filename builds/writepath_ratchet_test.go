package builds

import (
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"
)

const declaredLossFile = "testdata/writepath_declared_losses.txt"

func lossClasses(c *census) map[string]map[string]*finding {
	return map[string]map[string]*finding{
		"LOST_ELEM":   c.LostElem,
		"LOST_ATTR":   c.LostAttr,
		"ADDED_ELEM":  c.AddedElem,
		"ADDED_ATTR":  c.AddedAttr,
		"VALUE":       c.ValDiff,
		"REFORMATTED": c.ValDiffNumOnly,
		"TEXT":        c.TextDiff,
	}
}

func observedLosses(c *census) map[string]bool {
	got := map[string]bool{}
	for class, m := range lossClasses(c) {
		for path := range m {
			got[class+" "+path] = true
		}
	}
	return got
}

func readDeclaredLosses(t *testing.T) map[string]bool {
	t.Helper()

	raw, err := os.ReadFile(declaredLossFile)
	if err != nil {
		t.Fatalf("cannot read %s: %v — regenerate with WRITEPATH_RERECORD=1", declaredLossFile, err)
	}

	declared := map[string]bool{}
	for _, line := range strings.Split(string(raw), "\n") {
		line = strings.TrimSpace(line)
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		declared[line] = true
	}
	return declared
}

// TestWritePathRoundTripHasNoUndeclaredLoss is the gate the census's own header has named since the census was written.
func TestWritePathRoundTripHasNoUndeclaredLoss(t *testing.T) {
	dir := corpusDirForLoadedData(t)

	full := os.Getenv("CORPUS") != "" || os.Getenv("WRITEPATH_FULL") != ""
	limit := 300
	if full {
		limit = 0
	}

	c := runCensus(t, dir, limit)
	got := observedLosses(c)

	if os.Getenv("WRITEPATH_RERECORD") != "" {
		if !full {
			t.Fatal("WRITEPATH_RERECORD needs the whole corpus: re-run with WRITEPATH_FULL=1")
		}
		writeDeclaredLosses(t, got)
		t.Fatalf("re-recorded %s with %d paths; re-run without WRITEPATH_RERECORD", declaredLossFile, len(got))
	}

	declared := readDeclaredLosses(t)

	var undeclared []string
	for entry := range got {
		if !declared[entry] {
			undeclared = append(undeclared, entry)
		}
	}
	sort.Strings(undeclared)
	for _, entry := range undeclared {
		class, path, _ := strings.Cut(entry, " ")
		f := lossClasses(c)[class][path]
		t.Errorf("UNDECLARED write-path loss: %s %s (%d builds, %d occurrences, sample %s, e.g. %s)\n"+
			"    Either fix it, or — if it is a deliberate, justified omission — add the line\n"+
			"        %s\n"+
			"    to %s WITH a comment above it saying why.",
			class, path, f.Builds, f.Total, f.Sample, f.Example, entry, declaredLossFile)
	}

	if !full {
		t.Logf("sampled %d builds: the STALE-DECLARATION direction was NOT checked. "+
			"A declared path can only be proven gone by the full sweep (WRITEPATH_FULL=1).", c.Builds)
		return
	}

	var stale []string
	for entry := range declared {
		if !got[entry] {
			stale = append(stale, entry)
		}
	}
	sort.Strings(stale)
	for _, entry := range stale {
		t.Errorf("STALE declaration: %s no longer occurs over the whole corpus. Remove it from %s "+
			"— a baseline that keeps fixed entries stops describing the tree and starts excusing it.",
			entry, declaredLossFile)
	}
}

func writeDeclaredLosses(t *testing.T, got map[string]bool) {
	t.Helper()

	lines := make([]string, 0, len(got))
	for entry := range got {
		lines = append(lines, entry)
	}
	sort.Strings(lines)

	var b strings.Builder
	b.WriteString("# Every write-path difference the round trip currently produces, by CLASS and NAME.\n")
	b.WriteString("# Generated by TestWritePathRoundTripHasNoUndeclaredLoss with WRITEPATH_FULL=1\n")
	b.WriteString("# WRITEPATH_RERECORD=1. Deliberately carries NO counts: a ratchet with a number\n")
	b.WriteString("# and no names gets re-diagnosed as fresh breakage, and the counts move on every\n")
	b.WriteString("# corpus promotion while the names do not.\n#\n")
	b.WriteString("# A line here is a CLAIM THAT THE LOSS IS UNDERSTOOD, not permission to ignore it.\n")
	b.WriteString("# The reasoning for each group lives beside the field in pob/types_saved.go.\n\n")
	for _, l := range lines {
		fmt.Fprintln(&b, l)
	}

	if err := os.WriteFile(declaredLossFile, []byte(b.String()), 0o600); err != nil {
		t.Fatalf("writing %s: %v", declaredLossFile, err)
	}
}
