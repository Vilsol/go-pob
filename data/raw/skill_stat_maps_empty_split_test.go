package raw

import (
	"os"
	"regexp"
	"strconv"
	"strings"
	"testing"
)

var (
	ssmDeclaredEmptyRe = regexp.MustCompile(`(?m)^// (\d+) entries are empty because PoB DECLARES`)
	ssmLostEmptyRe     = regexp.MustCompile(`(?m)^// (\d+) are empty because every mod in them was OMITTED`)
	ssmEmptyModsRe     = regexp.MustCompile(`(?m)^\t\t\tMods: \[\]mod\.Mod\{\},$`)
	ssmScalarOmitRe    = regexp.MustCompile(`(?m)^//   - (\d+) nested mod group carrying the per-mod scalar`)
)

// TestSkillStatMapsEmptySplitDescribesTheFile grades the header's empty-entry split against the entries actually below it.
func TestSkillStatMapsEmptySplitDescribesTheFile(t *testing.T) {
	src, err := os.ReadFile("skill_stat_maps.go")
	if err != nil {
		t.Fatalf("cannot read the generated table: %v", err)
	}
	s := string(src)

	num := func(re *regexp.Regexp, what string) int {
		m := re.FindStringSubmatch(s)
		if m == nil {
			t.Fatalf("the header no longer states %s. It is generated by gopob's "+
				"skill-stat-maps emitter; if the wording moved, move this test with it rather "+
				"than deleting the assertion.", what)
		}
		n, err := strconv.Atoi(m[1])
		if err != nil {
			t.Fatalf("%s is not a number: %q", what, m[1])
		}
		return n
	}

	declared := num(ssmDeclaredEmptyRe, "how many entries PoB declares empty")
	lost := num(ssmLostEmptyRe, "how many entries were emptied by omission")
	actual := len(ssmEmptyModsRe.FindAllString(s, -1))

	if declared == 0 {
		t.Error("the header claims ZERO entries are declared-empty. PoB declares plenty; a zero " +
			"here means the emitter's classification broke, not that the class emptied.")
	}
	if lost == 0 {
		t.Error("the header claims ZERO entries were emptied by omission. That is the class this " +
			"split exists to name, and 14 of them were measured against the pinned PoB. A zero " +
			"means either every omission was fixed -- in which case delete this test deliberately " +
			"and say so -- or the classification stopped running.")
	}
	if got := declared + lost; got != actual {
		t.Errorf("the header's empty-entry split does not describe the file: it claims %d "+
			"declared-empty + %d emptied-by-omission = %d, and the table below holds %d entries "+
			"with an empty Mods list. Regenerate with `task data-regen -- --only skill-stat-maps`.",
			declared, lost, got, actual)
	}
}

// TestSkillStatMapsNoLongerDropsThePerModScalar is the RETIREMENT of a check that used to assert the opposite.
func TestSkillStatMapsNoLongerDropsThePerModScalar(t *testing.T) {
	src, err := os.ReadFile("skill_stat_maps.go")
	if err != nil {
		t.Fatalf("cannot read the generated table: %v", err)
	}
	s := string(src)

	if m := ssmScalarOmitRe.FindStringSubmatch(s); m != nil {
		t.Errorf("the header is omitting %s mod(s) for a per-mod scalar again. raw.StatMap has a "+
			"Groups field and the emitter fills it, so this reason should be unreachable -- the "+
			"likely cause is a regeneration from a dump written before oracle/skill_stat_map.lua "+
			"encoded groups. That dump has no 'groupCount' and the emitter refuses it; a header "+
			"carrying this line means the refusal was bypassed.", m[1])
	}
	for _, gone := range []string{"per-mod scalar 'div'", "per-mod scalar 'mult'"} {
		if strings.Contains(s, gone) {
			t.Errorf("the generated header still mentions %q as a drop", gone)
		}
	}

	for _, c := range []struct {
		skill, stat string
		groups      int
	}{
		{"RejuvenationTotem", "base_life_regeneration_rate_per_minute", 2},
		{"Ravenous", "ravenous_buff_magnitude", 2},
	} {
		e := SkillStatMaps[c.skill][c.stat]
		if e == nil {
			t.Errorf("%s/%s is absent from the table", c.skill, c.stat)
			continue
		}
		if len(e.Groups) != c.groups {
			t.Errorf("%s/%s carries %d groups, want %d -- these are the two entries the retired "+
				"omission described", c.skill, c.stat, len(e.Groups), c.groups)
		}
	}
}
