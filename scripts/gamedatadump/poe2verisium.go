package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

type poe2VerisiumCraft struct {
	OriginalBaseType int `json:"OriginalBaseType"`
	NewBaseType      int `json:"NewBaseType"`
}

// luaQuoted is string.format("%q", s).
func luaQuoted(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for i := 0; i < len(s); i++ {
		c := s[i]
		switch {
		case c == '"' || c == '\\':
			b.WriteByte('\\')
			b.WriteByte(c)
		case c == '\n':
			b.WriteString("\\\n")
		case c == '\r':
			b.WriteString("\\r")
		case c == 0:
			b.WriteString("\\0")
		case c < 32 || c == 127:
			b.WriteString("\\" + strconv.Itoa(int(c)))
		default:
			b.WriteByte(c)
		}
	}
	b.WriteByte('"')
	return b.String()
}

//pob2:block:src/Export/Scripts/miscdata.lua:196-204
//pob2:block:src/Modules/Utils.lua:19-61
//pob2:block:src/Modules/Utils.lua:94-102
func poe2VerisiumCraftsLua() (string, error) {
	crafts, err := poe2Table[poe2VerisiumCraft]("Expedition2VerisiumCrafts")
	if err != nil {
		return "", err
	}
	bases, err := poe2Table[poe2BaseItemType]("BaseItemTypes")
	if err != nil {
		return "", err
	}
	type craft struct{ baseTypeID, name string }
	verisiumCrafts := map[string][]craft{}
	for _, row := range crafts {
		if row.OriginalBaseType < 0 || row.OriginalBaseType >= len(bases) || row.NewBaseType < 0 || row.NewBaseType >= len(bases) {
			return "", fmt.Errorf("Expedition2VerisiumCrafts row names a base outside BaseItemTypes (%d rows)", len(bases))
		}
		sourceBase := bases[row.OriginalBaseType].Name
		verisiumCrafts[sourceBase] = append(verisiumCrafts[sourceBase], craft{bases[row.NewBaseType].ID, bases[row.NewBaseType].Name})
	}
	keys := make([]string, 0, len(verisiumCrafts))
	for k := range verisiumCrafts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var out strings.Builder
	w := func(s ...string) {
		for _, x := range s {
			_, _ = out.WriteString(x)
		}
	}
	w("-- This file is automatically generated, do not edit!\n-- Game data (c) Grinding Gear Games\n\n")
	w("-- A list of possible base type transformations in runeforging/mastering.\n\n")
	w("-- spell-checker: disable\nreturn {\n")
	for _, k := range keys {
		w("\t[", luaQuoted(k), "] = {\n")
		for _, c := range verisiumCrafts[k] {
			w("\t\t{\n")
			w("\t\t\t[\"baseTypeId\"] = ", luaQuoted(c.baseTypeID), ",\n")
			w("\t\t\t[\"name\"] = ", luaQuoted(c.name), ",\n")
			w("\t\t},\n")
		}
		w("\t},\n")
	}
	w("}\n")
	return out.String(), nil
}
