var poe2SkillTemplateNames = []string{"act_str", "act_dex", "act_int", "other", "minion", "spectre", "sup_str", "sup_dex", "sup_int"}

var poe2SkillArgsRe = regexp.MustCompile(`([0-9A-Za-z]+) (.+)`)

// poe2GemsExport is the part of skills.lua's state Gems.lua reads: the gems and trueGemNames sets the
// #skill directives fill.
type poe2GemsExport struct {
	t             *game.SkillTables
	clientStrings []game.ClientString
	gemEffectByID map[string]*game.GemEffect
	gems          map[string]bool
	trueGemNames  map[string]string
}

func newPoE2GemsExport() (*poe2GemsExport, error) {
	t, err := game.LoadSkillTables(gameDataContext(), poe2Version, assetCache())
	if err != nil {
		return nil, fmt.Errorf("%s skill tables: %w", poe2Version, err)
	}
	clientStrings, err := poe2Table[game.ClientString](game.ClientStringsTable)
	if err != nil {
		return nil, err
	}
	x := &poe2GemsExport{
		t: t, clientStrings: clientStrings, gemEffectByID: make(map[string]*game.GemEffect, len(t.GemEffects)),
		gems: map[string]bool{}, trueGemNames: map[string]string{},
	}
	for i := range t.GemEffects {
		if _, ok := x.gemEffectByID[t.GemEffects[i].ID]; !ok {
			x.gemEffectByID[t.GemEffects[i].ID] = &t.GemEffects[i]
		}
	}
	return x, nil
}

// processTemplateFile runs a skill template's #noGem and #skill directives; the rest of skills.lua's
// directives write Data/Skills, which Gems.lua does not read.
//
//pob2:block:src/Export/Main.lua:112-135
func (x *poe2GemsExport) processTemplateFile(pobDir, name string) error {
	text, err := os.ReadFile(filepath.Join(pobDir, "src", "Export", "Skills", name+".txt")) //nolint:gosec // the pinned PoB-PoE2 checkout
	if err != nil {
		return fmt.Errorf("template %s: %w", name, err)
	}
	noGem := false
	for _, line := range strings.Split(string(text), "\n") {
		m := templateLineRe.FindStringSubmatch(line)
		if m == nil {
			continue
		}
		switch m[1] {
		case "noGem":
			noGem = true
		case "skill":
			x.skill(m[2], &noGem)
		}
	}
	return nil
}

// skill is the part of the #skill directive that fills gems and trueGemNames.
//
//pob2:block:src/Export/Scripts/skills.lua:126-214
func (x *poe2GemsExport) skill(args string, noGem *bool) {
	grantedID := args
	if m := poe2SkillArgsRe.FindStringSubmatch(args); m != nil {
		grantedID = m[1]
	}
	granted := x.t.GrantedEffectByID(grantedID)
	if granted == nil {
		return
	}
	gemEffect := x.t.GemEffect(granted.Key)
	if gemEffect != nil {
		if skillGem := x.t.SkillGem(gemEffect.Key); skillGem != nil {
			if named := x.gemEffectByID[gemEffect.ID]; named.Name != "" {
				x.trueGemNames[gemEffect.ID] = named.Name
			}
			if !*noGem {
				x.gems[gemEffect.ID] = true
			}
		}
	}
	*noGem = false
}

// supportGem is dat("SupportGems"):GetRow("SkillGem", dat("SkillGems"):GetRow("BaseItemType",
// dat("BaseItemTypes"):GetRow("Id", id))).
func (x *poe2GemsExport) supportGem(baseItemTypeID string) *game.SupportGem {
	for _, base := range x.t.BaseItemTypes {
		if base.ID != baseItemTypeID {
			continue
		}
		for _, gem := range x.t.SkillGems {
			if gem.BaseItemType == base.Key {
				return x.t.SupportGem(gem.Key)
			}
		}
		return nil
	}
	return nil
}

//pob2:block:src/Export/Scripts/skills.lua:915-1009
func (x *poe2GemsExport) gemsLua() (string, error) {
	t := x.t
	var out strings.Builder
	w := func(s ...string) {
		for _, p := range s {
			out.WriteString(p)
		}
	}
	itoa := strconv.Itoa
	w("-- This file is automatically generated, do not edit!\n")
	w("-- Gem data (c) Grinding Gear Games\n\nreturn {\n")
	for gi := range t.SkillGems {
		skillGem := &t.SkillGems[gi]
		baseItem := &t.BaseItemTypes[skillGem.BaseItemType]
		for _, gemEffectKey := range skillGem.GemEffects {
			gemEffect := &t.GemEffects[gemEffectKey]
			if !x.gems[gemEffect.ID] {
				continue
			}
			granted := &t.GrantedEffects[gemEffect.GrantedEffect]
			var activeSkill *game.ActiveSkill
			if granted.ActiveSkill != nil {
				activeSkill = &t.ActiveSkills[*granted.ActiveSkill]
			}
			w("\t[\"", "Metadata/Items/Gems/SkillGem"+gemEffect.ID, "\"] = {\n")
			name := baseItem.Name
			switch {
			case poe2FullNameGems[baseItem.ID]:
			case x.trueGemNames[gemEffect.ID] != "":
				name = x.trueGemNames[gemEffect.ID]
			default:
				name = strings.ReplaceAll(baseItem.Name, " Support", "")
			}
			w("\t\tname = \"", poe2SanitiseText(name), "\",\n")
			if !skillGem.IsSupport() {
				if activeSkill == nil {
					return "", fmt.Errorf("gem %s's granted effect %s has no active skill", baseItem.ID, granted.ID)
				}
				w("\t\tbaseTypeName = \"", activeSkill.DisplayedName, "\",\n")
			}
			w("\t\tgameId = \"", baseItem.ID, "\",\n")
			w("\t\tvariantId = \"", gemEffect.ID, "\",\n")
			w("\t\tgrantedEffectId = \"", granted.ID, "\",\n")
			for count, set := range granted.AdditionalStatSets {
				w("\t\tadditionalStatSet"+itoa(count+1)+" = \"", t.GrantedEffectStatSets[set].ID, "\",\n")
			}
			for count, effect := range gemEffect.AdditionalGrantedEffects {
				w("\t\tadditionalGrantedEffectId"+itoa(count+1)+" = \"", t.GrantedEffects[effect].ID, "\",\n")
			}
			if len(gemEffect.GrantedEffectDisplayOrder) > 0 {
				order := make([]string, len(gemEffect.GrantedEffectDisplayOrder))
				for i, o := range gemEffect.GrantedEffectDisplayOrder {
					order[i] = itoa(o)
				}
				w("\t\tgrantedEffectDisplayOrder = { ", strings.Join(order, ", "), " },\n")
			}
			if gemEffect.SupportName != "" {
				w("\t\tsecondaryEffectName = \"", gemEffect.SupportName, "\",\n")
			}
			if skillGem.IsVaalVariant {
				w("\t\tvaalGem = true,\n")
			}
			gemType := ""
			hasGemType := false
			tagNames := []string{}
			w("\t\ttags = {\n")
			for _, tagKey := range gemEffect.GemTags {
				tag := &t.GemTags[tagKey]
				w("\t\t\t", tag.ID, " = true,\n")
				if tag.Name != "" {
					tagName := escapeGGGString(tag.Name)
					if !hasGemType {
						gemType, hasGemType = tagName, true
					} else {
						tagNames = append(tagNames, tagName)
					}
				}
			}
			w("\t\t},\n")
			weaponRequirement := []string{}
			if activeSkill != nil && activeSkill.WeaponRequirements != nil {
				restrictions := &t.ActiveSkillWeaponRequirements[*activeSkill.WeaponRequirements]
				if restrictions.String != nil {
					weaponRequirement = append(weaponRequirement, escapeGGGString(x.clientStrings[*restrictions.String].Text))
				} else {
					for _, class := range t.WeaponClasses(*granted.ActiveSkill) {
						if _, ok := poe2WeaponClassMap[class.ID]; ok {
							if class.ItemClassCategory == nil {
								return "", fmt.Errorf("item class %s has no category", class.ID)
							}
							weaponRequirement = append(weaponRequirement, escapeGGGString(t.ItemClassCategories[*class.ItemClassCategory].Text))
						}
					}
				}
			}
			if !hasGemType {
				return "", fmt.Errorf("gem %s has no named tag; skills.lua:982 writes nil", gemEffect.ID)
			}
			w("\t\tgemType = \"", gemType, "\",\n")
			if skillGem.IsSupport() {
				supportGem := x.supportGem(baseItem.ID)
				if supportGem == nil {
					return "", fmt.Errorf("support gem %s has no SupportGems row", baseItem.ID)
				}
				gemFamily := make([]string, len(supportGem.Family))
				for i, family := range supportGem.Family {
					gemFamily[i] = t.SupportGemFamilies[family].Text
				}
				if len(gemFamily) > 0 {
					w("\t\tgemFamily = \"", strings.Join(gemFamily, ", "), "\",\n")
				}
			}
			w("\t\ttagString = \"", strings.Join(tagNames, ", "), "\",\n")
			if len(weaponRequirement) > 0 {
				w("\t\tweaponRequirements = \"", strings.Join(weaponRequirement, ", "), "\",\n")
			}
			w("\t\treqStr = ", itoa(skillGem.StrengthRequirementPercent), ",\n")
			w("\t\treqDex = ", itoa(skillGem.DexterityRequirementPercent), ",\n")
			w("\t\treqInt = ", itoa(skillGem.IntelligenceRequirementPercent), ",\n")
			w("\t\tTier = ", itoa(skillGem.CraftingLevel), ",\n")
			naturalMaxLevel := 1
			if !skillGem.IsSupport() {
				naturalMaxLevel = len(t.GemLevelProgression(skillGem.Key))
			}
			if naturalMaxLevel <= 0 {
				naturalMaxLevel = 1
			}
			w("\t\tnaturalMaxLevel = ", itoa(naturalMaxLevel), ",\n")
			w("\t},\n")
		}
	}
	w("}")
	return out.String(), nil
}

// poe2GemsLuaFrom is Data/Gems.lua over the pin's skill templates at pobDir.
func poe2GemsLuaFrom(pobDir string) (string, error) {
	x, err := newPoE2GemsExport()
	if err != nil {
		return "", err
	}
	for _, name := range poe2SkillTemplateNames {
		if err := x.processTemplateFile(pobDir, name); err != nil {
			return "", err
		}
	}
	return x.gemsLua()
}

func dumpPoE2Gems() (any, error) {
	pobDir := os.Getenv("POB_DIR")
	if pobDir == "" {
		return nil, fmt.Errorf("POB_DIR is not set; the skill templates are the pinned PoB-PoE2's Export/Skills")
	}
	text, err := poe2GemsLuaFrom(pobDir)
	if err != nil {
		return nil, err
	}
	return map[string]string{"Data/Gems.lua": text}, nil
}
