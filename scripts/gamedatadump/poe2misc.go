package main

import (
	"fmt"
	"strings"

	"github.com/Vilsol/go-pob-data/loader"
)

const poe2Version = "0.5"

func poe2Table[T any](name string) ([]T, error) {
	rows, err := loader.LoadJSONTable[T](gameDataContext(), poe2Version, name, assetCache())
	if err != nil {
		return nil, fmt.Errorf("%s %s: %w", poe2Version, name, err)
	}
	if len(rows) == 0 {
		return nil, fmt.Errorf("%s %s has no rows", poe2Version, name)
	}
	return rows, nil
}

type poe2GameConstant struct {
	ID      string `json:"Id"`
	Value   int    `json:"Value"`
	Divisor int    `json:"Divisor"`
}

type poe2PlayerMinionIntrinsicStat struct {
	Key   int `json:"_key"`
	Stat  int `json:"Stat"`
	Value int `json:"Value"`
}

type poe2Stat struct {
	ID string `json:"Id"`
}

type poe2DefaultMonsterStat struct {
	Evasion          int     `json:"Evasion"`
	Accuracy         int     `json:"Accuracy"`
	MonsterLife      int     `json:"MonsterLife"`
	AllyLife         int     `json:"AllyLife"`
	Damage           float64 `json:"Damage"`
	MinionDamage     float64 `json:"MinionDamage"`
	Armour           int     `json:"Armour"`
	AilmentThreshold int     `json:"AilmentThreshold"`
	PoiseThreshold   int     `json:"PoiseThreshold"`
}

type poe2MinionGemLevelScaling struct {
	MinionLevel int `json:"MinionLevel"`
}

type poe2SkillTotemVariation struct {
	MonsterVarietiesKey *int `json:"MonsterVarietiesKey"`
	SkillTotemsKey      int  `json:"SkillTotemsKey"`
}

type poe2MonsterVariety struct {
	Name           string `json:"Name"`
	Mods           []int  `json:"Mods"`
	LifeMultiplier int    `json:"LifeMultiplier"`
}

type poe2Mod struct {
	ID string `json:"Id"`
}

type poe2MonsterMapDifficulty struct {
	MapLevel            int `json:"MapLevel"`
	LifePercentIncrease int `json:"LifePercentIncrease"`
}

type poe2MonsterMapBossDifficulty struct {
	MapLevel                   int `json:"MapLevel"`
	BossLifePercentIncrease    int `json:"BossLifePercentIncrease"`
	BossAilmentPercentDecrease int `json:"BossAilmentPercentDecrease"`
}

type poe2FlatPhysicalDamageValue struct {
	GemLevel int `json:"GemLevel"`
	MinPhys  int `json:"MinPhys"`
	MaxPhys  int `json:"MaxPhys"`
}

type poe2GoldRespecPrice struct {
	Cost int `json:"Cost"`
}

func dumpPoE2MiscData() (any, error) {
	text, err := poe2MiscLua()
	if err != nil {
		return nil, err
	}
	crafts, err := poe2VerisiumCraftsLua()
	if err != nil {
		return nil, err
	}
	return map[string]string{"Data/Misc.lua": text, "Data/VerisiumCrafts.lua": crafts}, nil
}

//pob2:block:src/Export/Scripts/miscdata.lua:3-173
func poe2MiscLua() (string, error) {
	defaultMonsterStats, err := poe2Table[poe2DefaultMonsterStat]("DefaultMonsterStats")
	if err != nil {
		return "", err
	}
	minionLevels, err := poe2Table[poe2MinionGemLevelScaling]("MinionGemLevelScaling")
	if err != nil {
		return "", err
	}
	gameConstants, err := poe2Table[poe2GameConstant]("GameConstants")
	if err != nil {
		return "", err
	}
	intrinsics, err := poe2Table[poe2PlayerMinionIntrinsicStat]("PlayerMinionIntrinsicStats")
	if err != nil {
		return "", err
	}
	stats, err := poe2Table[poe2Stat]("Stats")
	if err != nil {
		return "", err
	}
	totems, err := poe2Table[poe2SkillTotemVariation]("SkillTotemVariations")
	if err != nil {
		return "", err
	}
	varieties, err := poe2Table[poe2MonsterVariety]("MonsterVarieties")
	if err != nil {
		return "", err
	}
	mods, err := poe2Table[poe2Mod]("Mods")
	if err != nil {
		return "", err
	}
	mapDifficulty, err := poe2Table[poe2MonsterMapDifficulty]("MonsterMapDifficulty")
	if err != nil {
		return "", err
	}
	mapBossDifficulty, err := poe2Table[poe2MonsterMapBossDifficulty]("MonsterMapBossDifficulty")
	if err != nil {
		return "", err
	}
	flatPhys, err := poe2Table[poe2FlatPhysicalDamageValue]("FlatPhysicalDamageValues")
	if err != nil {
		return "", err
	}
	respec, err := poe2Table[poe2GoldRespecPrice]("GoldRespecPrices")
	if err != nil {
		return "", err
	}

	var out strings.Builder
	w := func(s string) { _, _ = out.WriteString(s) }
	w("-- This file is automatically generated, do not edit!\n\n")
	w("---@class MiscDataExport\n")
	w("local data = {}\n")
	var evasion, accuracy, life, allyLife, allyDamage, damage, armour, ailmentThreshold, poiseThreshold, minionLevel string
	for _, stats := range defaultMonsterStats {
		evasion += luaNumStr(float64(stats.Evasion)) + ", "
		accuracy += luaNumStr(float64(stats.Accuracy)) + ", "
		life += luaNumStr(float64(stats.MonsterLife)) + ", "
		allyLife += luaNumStr(float64(stats.AllyLife)) + ", "
		damage += f32(stats.Damage) + ", "
		allyDamage += f32(stats.MinionDamage) + ", "
		armour += luaNumStr(float64(stats.Armour)) + ", "
		ailmentThreshold += luaNumStr(float64(stats.AilmentThreshold)) + ", "
		poiseThreshold += luaNumStr(float64(stats.PoiseThreshold)) + ", "
	}
	w("-- From DefaultMonsterStats.dat\n")
	w("data.monsterEvasionTable = { " + evasion + "}\n")
	w("data.monsterAccuracyTable = { " + accuracy + "}\n")
	w("data.monsterLifeTable = { " + life + "}\n")
	w("data.monsterAllyLifeTable = { " + allyLife + "}\n")
	w("data.monsterDamageTable = { " + damage + "}\n")
	w("data.monsterAllyDamageTable = { " + allyDamage + "}\n")
	w("data.monsterArmourTable = { " + armour + "}\n")
	w("data.monsterAilmentThresholdTable = { " + ailmentThreshold + "}\n")
	w("data.monsterPoiseThresholdTable = { " + poiseThreshold + "}\n")
	w("\n")

	w("-- From MinionGemLevelScaling.dat\n")
	for _, level := range minionLevels {
		minionLevel += luaNumStr(float64(level.MinionLevel)) + ", "
	}
	w("data.minionLevelTable = { " + minionLevel + "}\n")
	w("\n")

	w("-- From GameConstants.dat\n")
	w("data.gameConstants = {\n")
	for _, row := range gameConstants {
		w("\t[\"" + row.ID + "\"] = " + luaNumStr(float64(row.Value)/float64(row.Divisor)) + ",\n")
	}
	w("}\n")

	w("-- From Metadata/Characters/Character.ot\n")
	w("data.characterConstants = {\n")
	if err := otConstants(poe2Version, "Metadata/Characters/Character.ot", []string{"Stats", "Pathfinding"}, &out); err != nil {
		return "", err
	}
	w("}\n")

	w("-- From Metadata/Monsters/Monster.ot\n")
	w("data.monsterConstants = {\n")
	if err := otConstants(poe2Version, "Metadata/Monsters/Monster.ot", []string{"Stats"}, &out); err != nil {
		return "", err
	}
	w("}\n")

	w("-- From PlayerMinionIntrinsicStats.dat\n")
	w("data.playerMinionIntrinsicStats = {\n")
	for _, row := range intrinsics {
		if row.Stat < 0 || row.Stat >= len(stats) {
			return "", fmt.Errorf("PlayerMinionIntrinsicStats row %d names stat %d of %d", row.Key, row.Stat, len(stats))
		}
		w("\t[\"" + stats[row.Stat].ID + "\"] = " + luaNumStr(float64(row.Value)) + ",\n")
	}
	w("}\n")

	totemMult := ""
	keys := map[int]bool{}
	for _, v := range totems {
		if !keys[v.SkillTotemsKey] {
			keys[v.SkillTotemsKey] = true
			mult := 1.0
			if v.MonsterVarietiesKey != nil {
				if *v.MonsterVarietiesKey < 0 || *v.MonsterVarietiesKey >= len(varieties) {
					return "", fmt.Errorf("SkillTotemVariations names monster variety %d of %d", *v.MonsterVarietiesKey, len(varieties))
				}
				mult = float64(varieties[*v.MonsterVarietiesKey].LifeMultiplier) / 100
			}
			totemMult += "[" + luaNumStr(float64(v.SkillTotemsKey)) + "] = " + luaNumStr(mult) + ", "
		}
	}
	w("-- From MonsterVarieties.dat combined with SkillTotemVariations.dat\n")
	w("data.totemLifeMult = { " + totemMult + "}\n")

	w("data.monsterVarietyLifeMult = {\n")
	cachedEntry := map[string]bool{}
	for _, row := range varieties {
		for _, m := range row.Mods {
			if m < 0 || m >= len(mods) {
				return "", fmt.Errorf("monster variety %q names mod %d of %d", row.Name, m, len(mods))
			}
			if mods[m].ID == "MonsterNecromancerRaisable" && !cachedEntry[row.Name] {
				w("\t[\"" + row.Name + "\"] = " + luaNumStr(float64(row.LifeMultiplier)/100) + ",\n")
				cachedEntry[row.Name] = true
				break
			}
		}
	}
	w("}\n")

	w("-- From MonsterMapDifficulty.dat\n")
	w("data.mapLevelLifeMult = { ")
	for _, row := range mapDifficulty {
		w("[" + luaNumStr(float64(row.MapLevel)) + "] = " + luaNumStr(1+float64(row.LifePercentIncrease)/100) + ", ")
	}
	w("}\n")

	var mapBossLifeMult, mapBossAilmentMult string
	for _, v := range mapBossDifficulty {
		mapBossLifeMult += "[" + luaNumStr(float64(v.MapLevel)) + "] = " + luaNumStr(1+float64(v.BossLifePercentIncrease)/100) + ", "
		mapBossAilmentMult += "[" + luaNumStr(float64(v.MapLevel)) + "] = " + luaNumStr(float64(100+v.BossAilmentPercentDecrease)/100) + ", "
	}
	w("-- From MonsterMapBossDifficulty.dat\n")
	w("data.mapLevelBossLifeMult = { " + mapBossLifeMult + "}\n")
	w("data.mapLevelBossAilmentMult = { " + mapBossAilmentMult + "}\n")
	w("\n")

	w("-- From FlatPhysicalDamageValues.dat\n")
	w("data.hollowPalmAddedPhys = {\n")
	for _, row := range flatPhys {
		w("\t[" + luaNumStr(float64(row.GemLevel)) + "] = { " + luaNumStr(float64(row.MinPhys)) + ", " + luaNumStr(float64(row.MaxPhys)) + " },\n")
	}
	w("}\n")

	w("-- From GoldRespecPrices.dat\n")
	w("data.goldRespecPrices = { ")
	for _, row := range respec {
		w(luaNumStr(float64(row.Cost)) + ", ")
	}
	w("}\n")

	w("return data\n")
	return out.String(), nil
}
