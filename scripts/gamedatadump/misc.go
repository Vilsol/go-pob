func f32(v float64) string { return luaNumStr(float64(float32(v))) }

//pob:block:src/Export/Scripts/miscdata.lua:55-71
func otConstants(path string, blocks []string, out *strings.Builder) error {
	b, err := loader.LoadFile(gameDataContext(), raw.LatestVersion, path, assetCache())
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	inWantedBlock := false
	for _, line := range strings.FieldsFunc(string(b), func(r rune) bool { return r == '\r' || r == '\n' }) {
		wanted := false
		for _, block := range blocks {
			wanted = wanted || strings.HasPrefix(line, block)
		}
		switch {
		case wanted:
			inWantedBlock = true
		case inWantedBlock && strings.HasPrefix(line, "}"):
			inWantedBlock = false
		case inWantedBlock && strings.Contains(line, "="):
			if m := otStatLineRe.FindStringSubmatch(otSpaceRe.ReplaceAllString(line, "")); m != nil {
				_, _ = out.WriteString("\t[\"" + m[1] + "\"] = " + m[2] + ",\n")
			}
		}
	}
	return nil
}

//pob:block:src/Export/Scripts/miscdata.lua:3-142
func miscLua() (string, error) {
	var out strings.Builder
	w := func(s string) { _, _ = out.WriteString(s) }
	w("-- This file is automatically generated, do not edit!\n\n")
	w("local data = ...\n")
	var evasion, accuracy, life, altLife1, altLife2, allyLife, allyDamage, damage, armour, ailmentThreshold, monsterPhysConversionMulti string
	for _, stats := range poe.DefaultMonsterStats {
		evasion += luaNumStr(float64(stats.Evasion)) + ", "
		accuracy += luaNumStr(float64(stats.Accuracy)) + ", "
		life += luaNumStr(float64(stats.MonsterLife)) + ", "
		altLife1 += luaNumStr(float64(stats.AltLife1)) + ", "
		altLife2 += luaNumStr(float64(stats.AltLife2)) + ", "
		allyLife += luaNumStr(float64(stats.MinionLife)) + ", "
		damage += f32(stats.Damage) + ", "
		allyDamage += f32(stats.MinionDamage) + ", "
		ailmentThreshold += luaNumStr(float64(stats.AilmentThreshold)) + ", "
		monsterPhysConversionMulti += luaNumStr(float64(stats.MonsterPhysConversionMulti)) + ", "
	}
	improvement := poe.GameConstantsByID["MonsterDamageReductionImprovement"]
	if improvement == nil {
		return "", fmt.Errorf("GameConstants has no MonsterDamageReductionImprovement")
	}
	for i := 1; i <= 100; i++ {
		armour += luaNumStr(math.Floor(float64(10+2*i)*math.Pow(1+float64(improvement.Value)/float64(improvement.Divisor)/100, float64(i)))) + ", "
	}
	w("-- From DefaultMonsterStats.dat\n")
	w("data.monsterEvasionTable = { " + evasion + "}\n")
	w("data.monsterAccuracyTable = { " + accuracy + "}\n")
	w("data.monsterLifeTable = { " + life + "}\n")
	w("data.monsterLifeTable2 = { " + altLife1 + "}\n")
	w("data.monsterLifeTable3 = { " + altLife2 + "}\n")
	w("data.monsterAllyLifeTable = { " + allyLife + "}\n")
	w("data.monsterDamageTable = { " + damage + "}\n")
	w("data.monsterAllyDamageTable = { " + allyDamage + "}\n")
	w("data.monsterArmourTable = { " + armour + "}\n")
	w("data.monsterAilmentThresholdTable = { " + ailmentThreshold + "}\n")
	w("data.monsterPhysConversionMultiTable = { " + monsterPhysConversionMulti + "}\n")

	w("-- From GameConstants.dat\n")
	w("data.gameConstants = {\n")
	for _, row := range poe.GameConstants {
		w("\t[\"" + row.ID + "\"] = " + luaNumStr(float64(row.Value)/float64(row.Divisor)) + ",\n")
	}
	w("}\n")

	w("-- From Metadata/Characters/Character.ot\n")
	w("data.characterConstants = {\n")
	if err := otConstants("Metadata/Characters/Character.ot", []string{"Stats", "Pathfinding"}, &out); err != nil {
		return "", err
	}
	w("}\n")

	w("-- From Metadata/Monsters/Monster.ot\n")
	w("data.monsterConstants = {\n")
	if err := otConstants("Metadata/Monsters/Monster.ot", []string{"Stats"}, &out); err != nil {
		return "", err
	}
	w("}\n")

	totemMult := ""
	keys := map[int]bool{}
	for _, v := range poe.SkillTotemVariations {
		if !keys[v.SkillTotemsKey] {
			keys[v.SkillTotemsKey] = true
			totemMult += "[" + luaNumStr(float64(v.SkillTotemsKey)) + "] = " + luaNumStr(float64(poe.MonsterVarieties[v.MonsterVarietiesKey].LifeMultiplier)/100) + ", "
		}
	}
	w("-- From MonsterVarieties.dat combined with SkillTotemVariations.dat\n")
	w("data.totemLifeMult = { " + totemMult + "}\n")

	w("data.monsterVarietyLifeMult = {\n")
	cachedEntry := map[string]bool{}
	for _, row := range poe.MonsterVarieties {
		for _, m := range row.ModsKeys {
			if poe.Mods[m].ID == "MonsterNecromancerRaisable" && !cachedEntry[row.Name] {
				w("\t[\"" + row.Name + "\"] = " + luaNumStr(float64(row.LifeMultiplier)/100) + ",\n")
				cachedEntry[row.Name] = true
				break
			}
		}
	}
	w("}\n")

	w("-- From MonsterMapDifficulty.dat\n")
	w("data.mapLevelLifeMult = { ")
	for _, row := range poe.MonsterMapDifficulties {
		w("[" + luaNumStr(float64(row.MapLevel)) + "] = " + luaNumStr(1+float64(row.LifePercentIncrease)/100) + ", ")
	}
	w("}\n")

	var mapBossLifeMult, mapBossAilmentMult string
	for _, v := range poe.MonsterMapBossDifficulties {
		mapBossLifeMult += "[" + luaNumStr(float64(v.MapLevel)) + "] = " + luaNumStr(1+float64(v.BossLifePercentIncrease)/100) + ", "
		mapBossAilmentMult += "[" + luaNumStr(float64(v.MapLevel)) + "] = " + luaNumStr(float64(100+v.BossAilmentPercentDecrease)/100) + ", "
	}
	w("-- From MonsterMapBossDifficulty.dat\n")
	w("data.mapLevelBossLifeMult = { " + mapBossLifeMult + "}\n")
	w("data.mapLevelBossAilmentMult = { " + mapBossAilmentMult + "}\n")

	w("-- From VillageBalancePerLevelShared.dat\n")
	w("data.goldRespecPrices = { ")
	for _, row := range poe.VillageBalancePerLevels {
		w(luaNumStr(float64(row.GoldRespecCost)) + ", ")
	}
	w("}\n")
	return out.String(), nil
}

var bossDirectiveUberRe, bossDirectiveRe = regexp.MustCompile(`([A-Za-z0-9]+) (.+) {([A-Za-z0-9]+)}`), regexp.MustCompile(`([A-Za-z0-9]+) (.+)`)

//pob:block:src/Export/Scripts/bossData.lua:367-385
//pob:block:src/Export/Scripts/bossData.lua:570
func bossesLua(pobDir string) (string, error) {
	b, err := os.ReadFile(filepath.Join(pobDir, "src", "Export", "Enemies", "Bosses.txt")) //nolint:gosec // the pinned PoB checkout
	if err != nil {
		return "", fmt.Errorf("template Bosses: %w", err)
	}
	var out strings.Builder
	w := func(s string) { _, _ = out.WriteString(s) }
	w("-- This file is automatically generated, do not edit!\n")
	for _, line := range strings.Split(strings.TrimSuffix(string(b), "\n"), "\n") {
		line = strings.TrimSuffix(line, "\r")
		m := templateLineRe.FindStringSubmatch(line)
		if m == nil {
			w(line + "\n")
			continue
		}
		if m[1] != "boss" {
			fmt.Fprintf(os.Stderr, "Unknown directive '%s'\n", m[1])
			continue
		}
		args := m[2]
		var displayName, monsterID string
		isUber := false
		if d := bossDirectiveUberRe.FindStringSubmatch(args); d != nil {
			displayName, monsterID, isUber = d[1], d[2], true
		} else if d := bossDirectiveRe.FindStringSubmatch(args); d != nil {
			displayName, monsterID = d[1], d[2]
		}
		var monsterType *poe.MonsterType
		for _, t := range poe.MonsterTypes {
			if t.ID == monsterID {
				monsterType = t
				break
			}
		}
		if monsterType == nil {
			fmt.Fprintf(os.Stderr, "Invalid Type: %s\n", monsterID)
			continue
		}
		w("bosses[\"" + displayName + "\"] = {\n")
		w("\tarmourMult = " + luaNumStr(float64(monsterType.Armour)) + ",\n")
		w("\tevasionMult = " + luaNumStr(float64(monsterType.Evasion)) + ",\n")
		w("\tisUber = " + fmt.Sprint(isUber) + ",\n")
		w("}\n")
	}
	return out.String(), nil
}

func dumpCoreConstantsData() (any, error) {
	pobDir := os.Getenv("POB_DIR")
	if pobDir == "" {
		return nil, fmt.Errorf("POB_DIR is not set; the boss list is the pinned PoB's Export/Enemies/Bosses.txt")
	}
	ctx, cache := gameDataContext(), assetCache()
	for _, t := range []struct {
		name string
		init func() error
	}{
		{"DefaultMonsterStats", func() error { return poe.InitializeDefaultMonsterStats(ctx, raw.LatestVersion, cache) }},
		{"GameConstants", func() error { return poe.InitializeGameConstants(ctx, raw.LatestVersion, cache) }},
		{"MonsterVarieties", func() error { return poe.InitializeMonsterVarieties(ctx, raw.LatestVersion, cache) }},
		{"MonsterTypes", func() error { return poe.InitializeMonsterTypes(ctx, raw.LatestVersion, cache) }},
		{"SkillTotemVariations", func() error { return poe.InitializeSkillTotemVariations(ctx, raw.LatestVersion, cache) }},
		{"Stats", func() error { return poe.InitializeStats(ctx, raw.LatestVersion, cache) }},
		{"Mods", func() error { return poe.InitializeMods(ctx, raw.LatestVersion, cache) }},
		{"MonsterMapDifficulty", func() error { return poe.InitializeMonsterMapDifficulties(ctx, raw.LatestVersion, cache) }},
		{"MonsterMapBossDifficulty", func() error { return poe.InitializeMonsterMapBossDifficulties(ctx, raw.LatestVersion, cache) }},
		{"VillageBalancePerLevelShared", func() error { return poe.InitializeVillageBalancePerLevels(ctx, raw.LatestVersion, cache) }},
	} {
		if err := t.init(); err != nil {
			return nil, fmt.Errorf("%s: %w", t.name, err)
		}
	}
	misc, err := miscLua()
	if err != nil {
		return nil, err
	}
	bosses, err := bossesLua(pobDir)
	if err != nil {
		return nil, err
	}
	return map[string]string{"Data/Misc.lua": misc, "Data/Bosses.lua": bosses}, nil
}
