package main

import (
	"fmt"
	"regexp"
	"sort"
	"strings"
)

type poe2ScalableStat struct {
	ID         string `json:"Id"`
	IsScalable bool   `json:"IsScalable"`
}

// poe2Scalability is one placeholder's entry; a nil isScalable is Lua's `scalability[statNum]` past the
// descriptor's last stat.
type poe2Scalability struct {
	isScalable *bool
	formats    []string
}

var (
	poe2ScalabilityPlaceholderRe = regexp.MustCompile(`[+-]?\{[^{}]*\}`)
	poe2ScalabilityDigitRe       = regexp.MustCompile(`\d`)
)

//pob2:src/Export/statdesc.lua:435-474
func (e *poe2Describer) describeScalability(stats []poe2ScalableStat) (map[string][]*poe2Scalability, error) {
	isScalable := map[string]bool{}
	for _, s := range stats {
		isScalable[s.ID] = s.IsScalable
	}
	keys := make([]string, 0, len(e.descriptors))
	for stat := range e.descriptors {
		keys = append(keys, stat)
	}
	sort.Strings(keys)

	out := map[string][]*poe2Scalability{}
	for _, stat := range keys {
		statDescription := e.descriptors[stat]
		if statDescription.stats == nil {
			continue
		}
		var scalability []bool
		for _, s := range statDescription.stats {
			v, ok := isScalable[s]
			if !ok {
				return nil, fmt.Errorf("%s is not a Stats row", s)
			}
			scalability = append(scalability, v)
		}
		for _, wordings := range statDescription.variants {
			wordingFormats := map[int][]string{}
			for _, format := range wordings.Specs {
				if v, ok := format.V.(float64); ok {
					wordingFormats[int(v)] = append(wordingFormats[int(v)], format.K)
				}
			}
			var inOrderScalability []*poe2Scalability
			strippedLine := poe2ScalabilityPlaceholderRe.ReplaceAllStringFunc(wordings.Text, func(num string) string {
				statNum := 1
				if d := poe2ScalabilityDigitRe.FindString(num); d != "" {
					statNum = int(d[0]-'0') + 1
				}
				entry := &poe2Scalability{formats: wordingFormats[statNum]}
				if statNum <= len(scalability) {
					entry.isScalable = &scalability[statNum-1]
				}
				inOrderScalability = append(inOrderScalability, entry)
				return "#"
			})
			prior, ok := out[strippedLine]
			if !ok {
				out[strippedLine] = inOrderScalability
				continue
			}
			for j := range prior {
				if len(prior[j].formats) > len(wordingFormats[j+1]) {
					if j >= len(inOrderScalability) {
						return nil, fmt.Errorf("%q: placeholder %d has no counterpart", strippedLine, j+1)
					}
					prior[j] = inOrderScalability[j]
				}
			}
		}
	}
	return out, nil
}

//pob2:block:src/Export/Scripts/modScalability.lua:1-37
func poe2ModScalabilityLua() (string, error) {
	var stats []poe2ScalableStat
	var err error
	poe2TableInto(&stats, "Stats", &err)
	if err != nil {
		return "", err
	}
	describer, err := poe2LoadStatFile("stat_descriptions")
	if err != nil {
		return "", err
	}
	scalabilityLines, err := describer.describeScalability(stats)
	if err != nil {
		return "", err
	}
	lines := make([]string, 0, len(scalabilityLines))
	for line := range scalabilityLines {
		lines = append(lines, line)
	}
	sort.Strings(lines)

	var out strings.Builder
	out.WriteString("-- This file is automatically generated, do not edit!\n")
	out.WriteString("-- Item data (c) Grinding Gear Games\n\nreturn {\n")
	for _, line := range lines {
		scalability := scalabilityLines[line]
		out.WriteString("\t[\"" + line + "\"] = { ")
		for i, scalable := range scalability {
			isScalable := "nil"
			if scalable.isScalable != nil {
				isScalable = fmt.Sprint(*scalable.isScalable)
			}
			out.WriteString("{ isScalable = " + isScalable)
			if scalable.formats != nil {
				out.WriteString(", formats = { ")
				for j, format := range scalable.formats {
					out.WriteString("\"" + format + "\"")
					if j < len(scalable.formats)-1 {
						out.WriteString(", ")
					}
				}
				out.WriteString(" }")
			}
			out.WriteString(" }")
			if i < len(scalability)-1 {
				out.WriteString(", ")
			}
		}
		out.WriteString(" },\n")
	}
	out.WriteString("}")
	return out.String(), nil
}

func dumpPoE2ModScalability() (any, error) {
	text, err := poe2ModScalabilityLua()
	if err != nil {
		return nil, err
	}
	if strings.Count(text, "\n") < 1000 {
		return nil, fmt.Errorf("Data/ModScalability.lua holds %d rows; the stat descriptions did not load", strings.Count(text, "\n"))
	}
	return map[string]string{"Data/ModScalability.lua": text}, nil
}
