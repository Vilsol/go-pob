package gateversions

import (
	"fmt"
	"strings"
)

type Row struct {
	Version       string
	OracleTest    string
	CorpusTest    string
	Authoritative bool
}

var Table = []Row{
	{Version: "3.29", OracleTest: "TestCorpus3_29VsOracle", CorpusTest: "TestCorpus3_29", Authoritative: true},
}

const (
	RefusalAuthoritativeFmt = "REFUSING: GATE_VERSIONS declares %d authoritative versions, expected exactly 1."
	RefusalEmpty            = "REFUSING: GATE_VERSIONS is empty, so there are no gate tests to name."
)

func Authoritative() (Row, error) {
	var found Row
	hits := 0
	for _, r := range Table {
		if r.Authoritative {
			found = r
			hits++
		}
	}
	if hits != 1 {
		return Row{}, fmt.Errorf(RefusalAuthoritativeFmt, hits) //nolint:err113 // verbatim shell text
	}
	return found, nil
}

func AllTests() (string, error) {
	parts := make([]string, 0, len(Table)*2)
	for _, r := range Table {
		parts = append(parts, r.OracleTest, r.CorpusTest)
	}
	if len(parts) == 0 {
		return "", fmt.Errorf("%s", RefusalEmpty) //nolint:err113 // verbatim shell text
	}
	return strings.Join(parts, "|"), nil
}

func (r Row) pipe() string {
	a := "0"
	if r.Authoritative {
		a = "1"
	}
	return strings.Join([]string{r.Version, r.OracleTest, r.CorpusTest, a}, "|")
}

func Shell() string {
	var b strings.Builder
	b.WriteString("# generated by `gopob gate-versions --sh` — edit the table in Go, not here\n")
	b.WriteString("GATE_VERSIONS=(\n")
	for _, r := range Table {
		fmt.Fprintf(&b, "  %q\n", r.pipe())
	}
	b.WriteString(")\n")
	b.WriteString("gv_field() { cut -d'|' -f\"$2\" <<<\"$1\"; }\n")

	if row, err := Authoritative(); err != nil {
		fmt.Fprintf(&b, "authoritative_row() { echo %q >&2; return 1; }\n", err.Error())
	} else {
		fmt.Fprintf(&b, "authoritative_row() { echo %q; }\n", row.pipe())
	}
	if all, err := AllTests(); err != nil {
		fmt.Fprintf(&b, "gv_all_tests() { echo %q >&2; return 1; }\n", err.Error())
	} else {
		fmt.Fprintf(&b, "gv_all_tests() { echo %q; }\n", all)
	}
	return b.String()
}

func TSV() string {
	var b strings.Builder
	for _, r := range Table {
		a := "0"
		if r.Authoritative {
			a = "1"
		}
		fmt.Fprintf(&b, "%s\t%s\t%s\t%s\n", r.Version, r.OracleTest, r.CorpusTest, a)
	}
	return b.String()
}
