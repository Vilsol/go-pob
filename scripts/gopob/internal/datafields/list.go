package datafields

import (
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"

	"github.com/Vilsol/go-pob-data/fields"
)

const (
	Format   = "go-pob-data-fields/2"
	FormatV1 = "go-pob-data-fields/1"
	KeepAll  = "*"
)

func Published(version string) (*List, error) {
	pub, ok := fields.For(version)
	if !ok {
		return nil, fmt.Errorf("go-pob-data publishes no field list for %s", version)
	}
	l := &List{Format: pub.Format, DataModule: pub.DataModule, Version: pub.Version, Assets: map[string]AssetList{}}
	for path, a := range pub.Assets {
		l.Assets[path] = AssetList{Type: a.Type, Keep: a.Keep}
	}
	return l, nil
}

type List struct {
	Format     string               `json:"format"`
	DataModule string               `json:"dataModule"`
	Version    string               `json:"version"`
	Assets     map[string]AssetList `json:"assets"`
	Whole      map[string][]string  `json:"wholeTypes"`
	TestOnly   map[string][]string  `json:"testOnlyReads,omitempty"`
	TestWhole  map[string][]string  `json:"testWholeSinks,omitempty"`
	Allowed    map[string][]string  `json:"allowlistedConversions,omitempty"`
	Unread     map[string][]string  `json:"droppedKeys"`
	Notes      []string             `json:"notes"`
}

type AssetList struct {
	Type  string   `json:"type"`
	Keep  []string `json:"keep"`
	paths []string
}

func (a AssetList) Paths() []string {
	if a.paths != nil {
		return a.paths
	}
	return a.Keep
}

func Build(res *Result, dataModule, version string) *List {
	l := &List{
		Format:     Format,
		DataModule: dataModule,
		Version:    version,
		Assets:     map[string]AssetList{},
		Whole:      map[string][]string{},
		TestOnly:   map[string][]string{},
		TestWhole:  map[string][]string{},
		Allowed:    map[string][]string{},
		Unread:     map[string][]string{},
		Notes: []string{
			"generated by `task data-fields`; do not edit",
			"a row is a msgpack map keyed by Go field name; `A.B` keeps key B inside the map(s) under A, through arrays and nil",
			"a path with no listed children keeps its whole value",
		},
	}
	used := map[FieldKey]bool{}
	for k := range res.Reads {
		used[k] = true
	}
	product := productReads(res)
	for typ, ws := range res.Whole {
		var why, testWhy []string
		for _, w := range ws {
			if w.Site.Test {
				testWhy = append(testWhy, w.Why+" @ "+w.Site.Pos)
				continue
			}
			why = append(why, w.Why+" @ "+w.Site.Pos)
		}
		if len(why) > 0 {
			sort.Strings(why)
			l.Whole[typ] = why
		}
		if len(testWhy) > 0 {
			sort.Strings(testWhy)
			l.TestWhole[typ] = testWhy
		}
	}
	for k, sites := range res.Reads {
		if product[k] {
			continue
		}
		if _, whole := l.Whole[k.Type]; whole {
			continue
		}
		var at []string
		for _, s := range sites {
			at = append(at, s.Pos)
		}
		sort.Strings(at)
		l.TestOnly[k.Type+"."+k.Field] = at
	}
	for k, sites := range res.Allowed {
		var at []string
		for _, s := range sites {
			at = append(at, s.Pos)
		}
		sort.Strings(at)
		l.Allowed[k] = at
	}
	for path, a := range res.Assets {
		keep := append([]string{}, expand(res, used, l.Whole, a.RowType, "", map[string]bool{})...)
		sort.Strings(keep)
		l.Unread[path] = append([]string{}, dropped(res, a.RowType, keep)...)
		if _, whole := l.Whole[a.RowType]; whole {
			l.Assets[path] = AssetList{Type: a.RowType, Keep: []string{KeepAll}, paths: keep}
			continue
		}
		l.Assets[path] = AssetList{Type: a.RowType, Keep: keep}
	}
	return l
}

func productReads(res *Result) map[FieldKey]bool {
	used := map[FieldKey]bool{}
	for k, sites := range res.Reads {
		for _, s := range sites {
			if !s.Test {
				used[k] = true
			}
		}
	}
	return used
}

func expand(res *Result, used map[FieldKey]bool, whole map[string][]string, typ, prefix string, stack map[string]bool) []string {
	st := res.Structs[typ]
	if st == nil || stack[typ] {
		return nil
	}
	stack[typ] = true
	defer delete(stack, typ)
	_, all := whole[typ]
	var out []string
	for _, f := range st.Fields {
		self := all || used[FieldKey{Type: typ, Field: f.Name}]
		var children []string
		if f.Nested != "" {
			children = expand(res, used, whole, f.Nested, prefix+f.Name+".", stack)
		}
		if self || len(children) > 0 {
			out = append(out, prefix+f.Name)
			out = append(out, children...)
		}
	}
	return out
}

func dropped(res *Result, typ string, keep []string) []string {
	var all []string
	var walk func(typ, prefix string, stack map[string]bool)
	walk = func(typ, prefix string, stack map[string]bool) {
		st := res.Structs[typ]
		if st == nil || stack[typ] {
			return
		}
		stack[typ] = true
		defer delete(stack, typ)
		for _, f := range st.Fields {
			all = append(all, prefix+f.Name)
			if f.Nested != "" {
				walk(f.Nested, prefix+f.Name+".", stack)
			}
		}
	}
	walk(typ, "", map[string]bool{})
	k := map[string]bool{}
	for _, p := range keep {
		k[p] = true
	}
	var out []string
	for _, p := range all {
		if k[p] {
			continue
		}
		parentKeptWhole := false
		for i := strings.LastIndex(p, "."); i > 0; i = strings.LastIndex(p[:i], ".") {
			if k[p[:i]] && !hasChild(keep, p[:i]) {
				parentKeptWhole = true
				break
			}
		}
		if !parentKeptWhole {
			out = append(out, p)
		}
	}
	sort.Strings(out)
	return out
}

func hasChild(keep []string, p string) bool {
	for _, x := range keep {
		if strings.HasPrefix(x, p+".") {
			return true
		}
	}
	return false
}

func (l *List) Marshal() ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetIndent("", "  ")
	enc.SetEscapeHTML(false)
	if err := enc.Encode(l); err != nil {
		return nil, fmt.Errorf("encode list: %w", err)
	}
	return buf.Bytes(), nil
}

func Load(path string) (*List, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("read list: %w", err)
	}
	var l List
	if err := json.Unmarshal(b, &l); err != nil {
		return nil, fmt.Errorf("%s: %w", path, err)
	}
	if l.Format != Format && l.Format != FormatV1 {
		return nil, fmt.Errorf("%s: format %q, this tool reads %q and %q", path, l.Format, Format, FormatV1)
	}
	return &l, nil
}

func Missing(committed, fresh *List) []string {
	var out []string
	for path, a := range fresh.Assets {
		c, ok := committed.Assets[path]
		if !ok {
			out = append(out, fmt.Sprintf("asset %s (%s) is loaded by go-pob but absent from the list", path, a.Type))
			continue
		}
		if len(c.Keep) == 1 && c.Keep[0] == KeepAll {
			continue
		}
		have := map[string]bool{}
		for _, p := range c.Keep {
			have[p] = true
		}
		for _, p := range a.Paths() {
			if !coveredBy(have, c.Keep, p) {
				out = append(out, fmt.Sprintf("%s: go-pob reads %s.%s, absent from the list", path, a.Type, p))
			}
		}
	}
	sort.Strings(out)
	return out
}

func coveredBy(have map[string]bool, keep []string, p string) bool {
	if have[p] {
		return true
	}
	for i := strings.LastIndex(p, "."); i > 0; i = strings.LastIndex(p[:i], ".") {
		if have[p[:i]] && !hasChild(keep, p[:i]) {
			return true
		}
	}
	return false
}
