const p2sUsage = "usage: poe2-skills-emit <dump.json> <out.go> <globals|statmap|overlay|minions>"

func poe2SkillsEmit(args []string) int {
	if len(args) != 3 {
		return oeUsage(p2sUsage)
	}
	body, err := os.ReadFile(args[0]) //nolint:gosec // the dump path is the caller's argument
	if err != nil {
		return oeRefuse(fmt.Sprintf("%s is not readable: %s", args[0], errnoText(err)))
	}
	var out string
	switch args[2] {
	case "globals":
		out, err = p2sGlobals(body)
	case "statmap":
		out, err = p2sStatMap(body)
	case "overlay":
		out, err = p2sOverlay(body)
	case "minions":
		out, err = p2sMinions(body)
	default:
		return oeUsage(p2sUsage)
	}
	if err != nil {
		return oeRefuse(fmt.Sprintf("%s: %s", args[0], err))
	}
	return oeWriteGo(args[1], out)
}

func p2sHeader(b *strings.Builder, table, cite string) {
	b.WriteString("// Code generated by scripts/gopob/regendata_poe2_skills.lua + `gopob poe2-skills-emit " + table + "` from the pinned PoB-PoE2. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `mise run data-regen --game poe2 -- --only poe2-skill-" + table + "`.\n//\n")
	b.WriteString("//pob2:" + cite + "\n\npackage poe2\n\n")
}

type p2sEnumRow struct {
	Name  string  `json:"name"`
	Value float64 `json:"value"`
}

func p2sGlobals(body []byte) (string, error) {
	var dump struct {
		SkillType   []p2sEnumRow `json:"skillType"`
		ModFlag     []p2sEnumRow `json:"modFlag"`
		KeywordFlag []p2sEnumRow `json:"keywordFlag"`
	}
	if err := p2eDecode(body, &dump); err != nil {
		return "", err
	}
	var b strings.Builder
	p2sHeader(&b, "globals", "src/Data/Global.lua:231-626")
	for _, e := range []struct {
		goName, goType, doc string
		rows                []p2sEnumRow
	}{
		{"SkillType", "int", "SkillType, the active skill types", dump.SkillType},
		{"ModFlag", "uint64", "ModFlag", dump.ModFlag},
		{"KeywordFlag", "uint64", "KeywordFlag", dump.KeywordFlag},
	} {
		if len(e.rows) == 0 {
			return "", fmt.Errorf("%s is empty", e.goName)
		}
		if !sort.SliceIsSorted(e.rows, func(i, j int) bool { return e.rows[i].Name < e.rows[j].Name }) {
			return "", fmt.Errorf("%s is not sorted by name", e.goName)
		}
		fmt.Fprintf(&b, "// %s is Global.lua's %s, %d names.\nvar %s = map[string]%s{\n", e.goName, e.doc, len(e.rows), e.goName, e.goType)
		for _, r := range e.rows {
			if r.Value < 0 || r.Value != float64(uint64(r.Value)) {
				return "", fmt.Errorf("%s.%s = %v is not a non-negative integer", e.goName, r.Name, r.Value)
			}
			v := strconv.FormatUint(uint64(r.Value), 10)
			if e.goType == "uint64" {
				v = fmt.Sprintf("0x%016X", uint64(r.Value))
			}
			fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(r.Name), v)
		}
		b.WriteString("}\n\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n", nil
}

type p2sScalars struct {
	Value *float64 `json:"value"`
	Mult  *float64 `json:"mult"`
	Div   *float64 `json:"div"`
	Base  *float64 `json:"base"`
}

func (s p2sScalars) fields(f *p2eFields) {
	for _, kv := range []struct {
		name string
		v    *float64
	}{{"Value", s.Value}, {"Mult", s.Mult}, {"Div", s.Div}, {"Base", s.Base}} {
		if kv.v != nil {
			f.parts = append(f.parts, kv.name+": "+p2eFloat(*kv.v), "Has"+kv.name+": true")
		}
	}
}

type p2sEntry struct {
	Stat      string            `json:"stat"`
	Items     []json.RawMessage `json:"items"`
	SkillFlag *string           `json:"skillFlag"`
	p2sScalars
}

type p2sGroup struct {
	Group []json.RawMessage `json:"group"`
	p2sScalars
}

// p2sMod compacts one mod's JSON, refusing anything that is not a mod object.
func p2sMod(raw json.RawMessage, where string) (string, error) {
	var probe map[string]json.RawMessage
	if err := json.Unmarshal(raw, &probe); err != nil || probe["name"] == nil {
		return "", fmt.Errorf("%s holds something that is not a mod", where)
	}
	var c bytes.Buffer
	if err := json.Compact(&c, raw); err != nil {
		return "", fmt.Errorf("%s has unreadable mod JSON: %w", where, err)
	}
	return c.String(), nil
}

func p2sMods(raws []json.RawMessage, where string) ([]string, error) {
	out := make([]string, len(raws))
	for i, raw := range raws {
		m, err := p2sMod(raw, fmt.Sprintf("%s[%d]", where, i+1))
		if err != nil {
			return nil, err
		}
		out[i] = m
	}
	return out, nil
}

func p2sEntryGo(e p2sEntry, where string) (string, error) {
	f := &p2eFields{}
	f.str("Stat", e.Stat)
	e.p2sScalars.fields(f)
	if e.SkillFlag != nil {
		f.parts = append(f.parts, "SkillFlag: "+strconv.Quote(*e.SkillFlag))
	}
	where += "." + e.Stat
	if len(e.Items) > 0 {
		items := make([]string, len(e.Items))
		for i, raw := range e.Items {
			iw := fmt.Sprintf("%s[%d]", where, i+1)
			var probe map[string]json.RawMessage
			if err := json.Unmarshal(raw, &probe); err != nil {
				return "", fmt.Errorf("%s is not an object", iw)
			}
			item := &p2eFields{}
			if _, isGroup := probe["group"]; isGroup {
				var g p2sGroup
				if err := p2eDecode(raw, &g); err != nil {
					return "", fmt.Errorf("%s: %w", iw, err)
				}
				mods, err := p2sMods(g.Group, iw)
				if err != nil {
					return "", err
				}
				item.raw("Group", p2eStrings(mods))
				g.p2sScalars.fields(item)
			} else {
				m, err := p2sMod(raw, iw)
				if err != nil {
					return "", err
				}
				item.str("Mod", m)
			}
			items[i] = item.String()
		}
		f.raw("Items", "[]StatMapItem{"+strings.Join(items, ", ")+"}")
	}
	return f.String(), nil
}

func p2sEntries(rows []p2sEntry, where string) (string, error) {
	if !sort.SliceIsSorted(rows, func(i, j int) bool { return rows[i].Stat < rows[j].Stat }) {
		return "", fmt.Errorf("%s is not sorted by stat; StatMapLookup binary-searches it", where)
	}
	parts := make([]string, len(rows))
	for i, r := range rows {
		if i > 0 && rows[i-1].Stat == r.Stat {
			return "", fmt.Errorf("%s has %s twice", where, r.Stat)
		}
		s, err := p2sEntryGo(r, where)
		if err != nil {
			return "", err
		}
		parts[i] = s
	}
	return strings.Join(parts, ", "), nil
}

func p2sStatMap(body []byte) (string, error) {
	var rows []p2sEntry
	if err := p2eDecode(body, &rows); err != nil {
		return "", err
	}
	if len(rows) == 0 {
		return "", fmt.Errorf("holds no stat map entries")
	}
	if _, err := p2sEntries(rows, "skillStatMap"); err != nil {
		return "", err
	}
	var b strings.Builder
	p2sHeader(&b, "statmap", "src/Data/SkillStatMap.lua:6-7")
	fmt.Fprintf(&b, "// SkillStatMap is data.skillStatMap, %d stats sorted by stat; mods are ModCache-style JSON without a source.\nvar SkillStatMap = []StatMapEntry{\n", len(rows))
	for _, r := range rows {
		s, err := p2sEntryGo(r, "skillStatMap")
		if err != nil {
			return "", err
		}
		b.WriteString("\t" + s + ",\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

