// TestRegenDataTableMatchesTheOriginal: THE GO TABLE AND THE PYTHON TABLE MUST NAME THE SAME GENERATORS.
func TestRegenDataTableMatchesTheOriginal(t *testing.T) {
	repo := repoRoot(t)

	rdAssertSubcommandsAreLive(t)

	b := difftest.ReadOriginal(t, repo, rdPy)
	if b == nil {
		return
	}
	nameRx := regexp.MustCompile(`(?m)^\s*name="([a-z0-9-]+)",`)
	nameHits := nameRx.FindAllStringSubmatch(string(b), -1)
	want := make([]string, 0, len(nameHits))
	for _, m := range nameHits {
		want = append(want, m[1])
	}
	if len(want) == 0 {
		t.Fatal("no generator names found in the original — the scan stopped matching")
	}
	got := make([]string, 0, len(rdGenerators))
	for _, g := range rdGenerators {
		got = append(got, g.name)
	}
	if len(got) != len(want) {
		t.Fatalf("the Go table has %d generators, the original has %d", len(got), len(want))
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("generator %d: Go has %q, the original has %q", i, got[i], want[i])
		}
	}
	outRx := regexp.MustCompile(`(?m)^\s*out="([^"]+)",`)
	outHits := outRx.FindAllStringSubmatch(string(b), -1)
	wantOut := make([]string, 0, len(outHits))
	for _, m := range outHits {
		wantOut = append(wantOut, m[1])
	}
	gotOut := make([]string, 0, len(rdGenerators))
	for _, g := range rdGenerators {
		gotOut = append(gotOut, g.out)
	}
	sort.Strings(wantOut)
	sort.Strings(gotOut)
	if fmt.Sprint(wantOut) != fmt.Sprint(gotOut) {
		t.Errorf("output paths differ:\n  go:  %v\n  py:  %v", gotOut, wantOut)
	}
}

func rdFormattedArtifact(marker string) string {
	return "package stub\n\n" + marker + "\nfunc Stub() {\n}\n"
}

func rdGzip(b []byte) ([]byte, error) {
	var out bytes.Buffer
	w, err := gzip.NewWriterLevel(&out, gzip.BestCompression)
	if err != nil {
		return nil, fmt.Errorf("gzip: %w", err)
	}
	if _, err := w.Write(b); err != nil {
		return nil, fmt.Errorf("gzip: %w", err)
	}
	if err := w.Close(); err != nil {
		return nil, fmt.Errorf("gzip: %w", err)
	}
	return out.Bytes(), nil
}

// TestRegenDataProducesAReproducibleGzip: `gzip -9 -n`, ASSERTED ON THE HEADER RATHER THAN BY COMPARISON.
func TestRegenDataProducesAReproducibleGzip(t *testing.T) {
	requirePOSIX(t)
	repo := repoRoot(t)
	bin := buildPort(t, repo)

	for _, side := range []struct {
		name   string
		goSide bool
	}{{"python", false}, {"go", true}} {
		if !side.goSide && originalsGone(t) {
			continue
		}
		t.Run(side.name, func(t *testing.T) {
			mk, binDir := rdSandbox(t, repo)
			sb, err := mk()
			if err != nil {
				t.Fatal(err)
			}
			args := []string{"--pob", "pob", "--only", "skill-table"}
			var cmd *exec.Cmd
			if side.goSide {
				cmd = exec.CommandContext(t.Context(), bin, append([]string{"regen-data"}, args...)...) //nolint:gosec // the harness's own binary
			} else {
				cmd = exec.CommandContext(t.Context(), "python3", append([]string{rdPy}, args...)...) //nolint:gosec // the harness's own sandbox script
			}
			cmd.Dir = sb
			cmd.Env = append(os.Environ(), "GOPOB_NICED=1",
				"PATH="+binDir+string(os.PathListSeparator)+os.Getenv("PATH"),
				"GOPOB_BIN="+filepath.Join(binDir, "gopob-stub"))
			if err := cmd.Run(); err != nil {
				t.Fatalf("in-place run failed: %v", err)
			}

			b, err := os.ReadFile(filepath.Join(sb, "testdata", "pob-skills", "skills.json.gz")) //nolint:gosec // the harness's own sandbox
			if err != nil {
				t.Fatal(err)
			}
			if len(b) < 10 || b[0] != 0x1f || b[1] != 0x8b {
				t.Fatalf("not a gzip stream: % x", b[:min(10, len(b))])
			}
			if b[3]&0x08 != 0 {
				t.Error("the gzip header carries a FILENAME — gzip -n was not passed, so the " +
					"artifact depends on the temp file's name")
			}
			if mtime := uint32(b[4]) | uint32(b[5])<<8 | uint32(b[6])<<16 | uint32(b[7])<<24; mtime != 0 {
				t.Errorf("the gzip header carries mtime %d — gzip -n was not passed, so two runs "+
					"of an UNCHANGED PoB produce different bytes", mtime)
			}
		})
	}
}

// TestRegenDataCheckLeavesTheRepositoryAlone: --check MUST NOT TOUCH THE REPOSITORY.
func TestRegenDataCheckLeavesTheRepositoryAlone(t *testing.T) {
	requirePOSIX(t)
	repo := repoRoot(t)
	bin := buildPort(t, repo)

	for _, side := range []struct {
		name   string
		goSide bool
	}{{"python", false}, {"go", true}} {
		if !side.goSide && originalsGone(t) {
			continue
		}
		t.Run(side.name, func(t *testing.T) {
			mk, binDir := rdSandbox(t, repo)
			sb, err := mk()
			if err != nil {
				t.Fatal(err)
			}
			artifact := filepath.Join(sb, "data", "raw", "skill_parts.go")
			before, err := os.ReadFile(artifact) //nolint:gosec // the harness's own sandbox
			if err != nil {
				t.Fatal(err)
			}
			if err := put(sb, ".stub-emit-drifts", ""); err != nil {
				t.Fatal(err)
			}

			args := []string{"--check", "--pob", "pob", "--only", "skill-parts"}
			var cmd *exec.Cmd
			if side.goSide {
				cmd = exec.CommandContext(t.Context(), bin, append([]string{"regen-data"}, args...)...) //nolint:gosec // the harness's own binary
			} else {
				cmd = exec.CommandContext(t.Context(), "python3", append([]string{rdPy}, args...)...) //nolint:gosec // the harness's own sandbox script
			}
			cmd.Dir = sb
			cmd.Env = append(os.Environ(), "GOPOB_NICED=1",
				"PATH="+binDir+string(os.PathListSeparator)+os.Getenv("PATH"),
				"GOPOB_BIN="+filepath.Join(binDir, "gopob-stub"))
			_ = cmd.Run()
			if got := cmd.ProcessState.ExitCode(); got != 1 {
				t.Fatalf("expected the STALE finding (1), got %d", got)
			}

			after, err := os.ReadFile(artifact) //nolint:gosec // the harness's own sandbox
			if err != nil {
				t.Fatal(err)
			}
			if !bytes.Equal(before, after) {
				t.Errorf("--check rewrote the committed artifact:\n  before %q\n  after  %q",
					before, after)
			}
		})
	}
}

func rdAssertSubcommandsAreLive(t *testing.T) {
	t.Helper()
	live := map[string]bool{}
	for _, c := range uDispatchCases(t) {
		live[c] = true
	}
	if len(live) < 50 {
		t.Fatalf("only %d subcommands parsed from the dispatch; the scan has stopped matching and "+
			"this check would accept anything", len(live))
	}
	for _, g := range rdGenerators {
		for _, p := range []string{g.emit, g.post} {
			if p == "" {
				continue
			}
			if sub := rdSub(p); !live[sub] {
				t.Errorf("generator %q names %q, which rdSub maps to %q — no such subcommand",
					g.name, p, sub)
			}
		}
	}
}
