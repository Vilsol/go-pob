var rdRefRx = regexp.MustCompile(`"((?:oracle|scripts)/[A-Za-z0-9_/]+\.(?:py|lua))"`)

func rdSandbox(t *testing.T, repo string) (func() (string, error), string) {
	t.Helper()
	pySrc := difftest.ReadOriginal(t, repo, rdPy)

	refs := map[string]bool{}
	for _, m := range rdRefRx.FindAllStringSubmatch(string(pySrc), -1) {
		refs[m[1]] = true
	}
	if pySrc == nil {
		refs = nil
	}
	if pySrc != nil && len(refs) < 15 {
		t.Fatalf("only %d oracle references found in %s — the scan stopped matching, and a "+
			"sandbox missing its emitters would fail for the wrong reason", len(refs), rdPy)
	}

	base := t.TempDir()
	binDir := filepath.Join(base, "bin")
	if err := os.MkdirAll(binDir, 0o750); err != nil {
		t.Fatal(err)
	}
	for name, body := range map[string]string{
		"setarch": rdStubSetarch, "mise": rdStubMise, "go": rdStubGo,
		"gopob-stub": rdStubGopob,
	} {
		if err := os.WriteFile(filepath.Join(binDir, name), []byte(body), 0o700); err != nil { //nolint:gosec
			t.Fatal(err)
		}
	}

	n := 0
	return func() (string, error) {
		n++
		sb := filepath.Join(base, fmt.Sprintf("sb%d", n))
		files := map[string]string{
			rdPy:                        string(pySrc),
			"scripts/pob_pin.py":        rdStubPobPin,
			"scripts/pob_pin.json":      "{\"content_sha256\": \"0123456789abcdef0123456789abcdef\"}\n",
			"scripts/port_manifest.txt": rdStubManifest,
			"scripts/chunk_init.py":     rdStubChunkInit,
		}
		for ref := range refs {
			if filepath.Ext(ref) == ".lua" {
				files[ref] = rdStubDump
			}
		}
		files[".luajit-det/bin/luajit"] = rdStubLuajit
		files[".stub-luajit-fallback"] = rdStubLuajit
		files["pob/src/.keep"] = ""

		for rel, b := range files {
			dst := filepath.Join(sb, rel)
			if err := os.MkdirAll(filepath.Dir(dst), 0o750); err != nil {
				return "", fmt.Errorf("sandbox: %w", err)
			}
			if err := os.WriteFile(dst, []byte(b), 0o700); err != nil { //nolint:gosec
				return "", fmt.Errorf("sandbox: %w", err)
			}
		}
		if err := os.MkdirAll(filepath.Join(sb, "data", "raw"), 0o750); err != nil {
			return "", fmt.Errorf("sandbox: %w", err)
		}
		if err := os.WriteFile(filepath.Join(sb, "data", "raw", "skill_parts.go"),
			[]byte(rdFormattedArtifact("// generated by a fixture emitter")), 0o600); err != nil {
			return "", fmt.Errorf("sandbox: %w", err)
		}
		if err := os.MkdirAll(filepath.Join(sb, "testdata", "pob-skills"), 0o750); err != nil {
			return "", fmt.Errorf("sandbox: %w", err)
		}
		gz, err := rdGzip([]byte("{\"committed\":true}\n"))
		if err != nil {
			return "", fmt.Errorf("sandbox: %w", err)
		}
		if err := os.WriteFile(filepath.Join(sb, "testdata", "pob-skills", "skills.json.gz"),
			gz, 0o600); err != nil {
			return "", fmt.Errorf("sandbox: %w", err)
		}
		if err := os.WriteFile(filepath.Join(sb, "data", "raw", "skill_weapon_types.go"),
			[]byte(rdFormattedArtifact("// from stdin: {\"committed\":true}")), 0o600); err != nil {
			return "", fmt.Errorf("sandbox: %w", err)
		}
		return sb, nil
	}, binDir
}

