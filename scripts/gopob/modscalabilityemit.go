package main

import (
	"fmt"
	"os"
	"strings"
)

// mod-scalability-emit turns scripts/gamedatadump mod-scalability's dump into data/raw/mod_scalability.go.
//
// ⚠️ THIS EMITTER HAS NO PYTHON ORIGINAL AND IS NOT A PORT. Every other row of `task data-regen`
// replaced an oracle/*_emit.py; the fold finished before this table existed, so there is nothing to
// grade it differentially against and its refusals carry //go-only markers rather than a
// counterpart in the frozen corpus.
//
// ⚠️ THE HEADER TEXT IS THE PRODUCT, NOT DECORATION. `task data-regen -- --check` regenerates into
// a temp tree and compares bytes, so a reflowed sentence below is a diff.

const msHeader = `package raw

import "strings"

// CODE GENERATED BY scripts/gamedatadump mod-scalability + ` + "`gopob mod-scalability-emit`" + ` FROM %s. DO NOT EDIT.
// Regenerate with ` + "`task data-regen -- --only mod-scalability`" + ` after a PoB pin bump.

// ModScalability mirrors PoB's data.modScalability (src/Data/ModScalability.lua), keyed by a mod
// line whose every value has been replaced with ` + "`#`" + `.
//
// It is the table itemLib.applyRange consults FIRST (src/Modules/ItemTools.lua:184-296). The
// pre-3.20 heuristic below it at :297-350 is the FALLBACK, reached only when the lookup misses --
// and go-pob ported the fallback alone until 2026-09-02, so it took the rare arm on every line.
//
// ⚠️ THE KEY IS THE STRIPPED LINE WITH ` + "`+#`" + ` COLLAPSED TO ` + "`#`" + `, which is why
// ` + "`+#%% to all Elemental Resistances`" + ` is stored, and looked up, without its plus. The
// SUBSTITUTION still happens into the ` + "`+#`" + ` form, so the sign survives into the output.
//
// ⚠️ AN EMPTY ENTRY LIST IS A REAL STATE. ` + "`\"\"`" + ` has one upstream, and applyRange keys
// its arm selection on the KEY'S EXISTENCE, not on the list being non-empty: an empty list still
// takes the scalability arm and substitutes every value back unformatted.
//
// ⚠️ ENTRY ORDER IS POSITIONAL AGAINST THE LINE'S VALUES. ItemTools.lua:187 walks the entries with
// ipairs and formats ` + "`scalableValues[i]`" + `, so entry 2 governs the second ` + "`#`" + ` in
// the key. The dumper preserves PoB's order; sorting them would format the wrong number.
type ModScalabilityEntry struct {
	// IsScalable gates the value/base scalars at ItemTools.lua:285. false is a MEANING, not an
	// absence -- an unscalable value is formatted with both scalars forced to 1.
	IsScalable bool
	// Formats is GGG's stat_descriptions format list, verbatim. applyRange reads it as an
	// if-chain (ItemTools.lua:191-283) in which the LAST recognised token wins, and silently
	// ignores every token it does not name -- "negate" is 3086 of the 3823 rows that carry any
	// format and reaches no branch at all.
	Formats []string
}
`

// msSeparators are the bytes the row encoding below splits on; no key or format may hold one.
const msSeparators = "\x1c\x1d\x1e\x1f"

// msGoStr is a Go string literal for a row: oeGoStr, whose JSON escapes spell the separators as \u001c..\u001f,
// rewritten into Go's \x1c..\x1f.
func msGoStr(s string) string {
	q := oeGoStr(s)
	for _, c := range []string{"1c", "1d", "1e", "1f"} {
		q = strings.ReplaceAll(q, `\u00`+c, `\x`+c)
	}
	return q
}

// msDecoder is emitted with the table. The table is one string per row rather than a map literal: as code, 15199
// rows were about 7 MB of the wasm module and the largest single cost of starting it (the 3.29 table took
// 338 ms of the 1.1 s package init in Chromium); as constant strings they are data, decoded by one loop.
const msDecoder = `
var ModScalability = decodeModScalability(modScalabilityRows[:])

// decodeModScalability reads modScalabilityRows. A row is the key, U+001F, then its entries separated by U+001D
// (none for an empty list). An entry is a flag digit -- '0' plus 1 for IsScalable and 2 when Formats is present
// (possibly empty) -- followed by each format behind a U+001C.
func decodeModScalability(rows []string) map[string][]ModScalabilityEntry {
	m := make(map[string][]ModScalabilityEntry, len(rows))
	for _, row := range rows {
		key, body, _ := strings.Cut(row, "\x1f")
		if body == "" {
			m[key] = []ModScalabilityEntry{}
			continue
		}
		parts := strings.Split(body, "\x1d")
		entries := make([]ModScalabilityEntry, len(parts))
		for i, part := range parts {
			flag := part[0] - '0'
			entries[i].IsScalable = flag&1 != 0
			if flag&2 != 0 {
				entries[i].Formats = []string{}
				if len(part) > 1 {
					entries[i].Formats = strings.Split(part[2:], "\x1c")
				}
			}
		}
		m[key] = entries
	}
	return m
}
`

func modScalabilityEmit(argv []string) int {
	//go-only: no python original — the fold finished before this table existed, so the usage line
	// names the SUBCOMMAND rather than an oracle/*_emit.py that never got written.
	if len(argv) != 2 {
		return oeUsage("usage: gopob mod-scalability-emit <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	rows := oeObject(dump["rows"])

	// REFUSE rather than emit a plausible empty file.
	//
	// ⚠️ AN EMPTY TABLE HERE IS INVISIBLE DOWNSTREAM: every lookup misses, applyRange falls back to
	// the legacy arm, and the tree behaves EXACTLY as it did before the port. There is no crash, no
	// NaN and no absent key -- only the value differences this table exists to remove, which is the
	// state a green gate cannot distinguish from success.
	//
	//go-only: this emitter has no python original; see the file header.
	if len(rows) == 0 {
		return oeRefuse("the dump has no modScalability rows. PoB has carried the table since " +
			"3.20; zero means data.modScalability moved or the dumper ran against a checkout " +
			"without src/Data/ModScalability.lua.")
	}

	var b strings.Builder
	fmt.Fprintf(&b, msHeader, oeVersion(dump))
	b.WriteString(msDecoder)
	b.WriteString("\nvar modScalabilityRows = [...]string{\n")

	entries, withFormats, empties := 0, 0, 0
	for _, key := range oeSortedKeys(rows) {
		//go-only: this emitter has no python original; see the file header.
		if strings.ContainsAny(key, msSeparators) {
			return oeRefuse(fmt.Sprintf("modScalability key %s holds a separator byte (U+001C..U+001F) "+
				"of the row encoding", oeGoStr(key)))
		}
		list := oeArray(rows[key])
		if len(list) == 0 {
			empties++
			fmt.Fprintf(&b, "\t%s,\n", msGoStr(key+"\x1f"))
			continue
		}
		parts := make([]string, 0, len(list))
		for i, raw := range list {
			entry := oeObject(raw)
			if entry == nil {
				//go-only: this emitter has no python original; see the file header.
				return oeRefuse(fmt.Sprintf("modScalability[%s][%d] is not an object; the "+
					"dumper emits one per entry, so the dump is truncated or hand-edited",
					oeGoStr(key), i+1))
			}
			flag := byte('0')
			if oeGoBool(entry["isScalable"]) == "true" {
				flag |= 1
			}
			var fmts strings.Builder
			if list := oeArray(entry["formats"]); list != nil {
				withFormats++
				flag |= 2
				for _, f := range list {
					name := oeStr(f)
					//go-only: this emitter has no python original; see the file header.
					if strings.ContainsAny(name, msSeparators) {
						return oeRefuse(fmt.Sprintf("modScalability[%s][%d] has a format holding a separator "+
							"byte (U+001C..U+001F) of the row encoding", oeGoStr(key), i+1))
					}
					fmts.WriteString("\x1c" + name)
				}
			}
			parts = append(parts, string(flag)+fmts.String())
			entries++
		}
		fmt.Fprintf(&b, "\t%s,\n", msGoStr(key+"\x1f"+strings.Join(parts, "\x1d")))
	}
	b.WriteString("}\n")

	if rc := oeWriteGo(argv[1], b.String()); rc != 0 {
		return rc
	}
	fmt.Fprintf(os.Stderr, "wrote %s (%d rows, %d with no entries, %d entries, %d with formats)\n",
		argv[1], len(rows), empties, entries, withFormats)
	return 0
}
