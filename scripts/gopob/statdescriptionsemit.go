func oracleStatDescriptionsEmit(argv []string) int {
	if len(argv) != 2 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeUsage("usage: stat-descriptions-emit <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	scopes := oeObject(dump["scopes"])
	if _, ok := scopes["stat_descriptions"]; !ok {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump carries no stat_descriptions scope. Re-run go run ./scripts/gamedatadump stat-descriptions.")
	}

	limitValue := func(v any) any {
		if n, ok := v.(json.Number); ok {
			return n
		}
		return nil
	}
	for name, s := range scopes {
		for idx, d := range oeObject(oeObject(s)["descriptors"]) {
			for i, v := range oeArray(oeObject(d)["variants"]) {
				variant := oeObject(v)
				var limits []any
				for _, l := range oeArray(variant["limit"]) {
					pair := oeArray(l)
					if len(pair) != 2 {
						//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
						return oeRefuse(fmt.Sprintf("scope %s descriptor %s variant %d has a limit that is not a pair", name, idx, i))
					}
					limit := map[string]any{}
					if pair[0] == "!" {
						limit["not"] = true
						limit["hi"] = limitValue(pair[1])
					} else {
						if lo := limitValue(pair[0]); lo != nil {
							limit["lo"] = lo
						}
						if hi := limitValue(pair[1]); hi != nil {
							limit["hi"] = hi
						}
					}
					limits = append(limits, limit)
				}
				variant["limit"] = limits
				var specs []any
				for _, sp := range oeArray(variant["specs"]) {
					spec := oeObject(sp)
					if _, ok := spec["v"].(json.Number); ok {
						specs = append(specs, spec)
					} else if spec["k"] != "reminderstring" && spec["k"] != "canonical_line" {
						//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
						return oeRefuse(fmt.Sprintf("scope %s descriptor %s variant %d has a %v spec without a stat index", name, idx, i, spec["k"]))
					}
				}
				variant["specs"] = specs
			}
		}
	}

	version, _ := dump["version"].(string)
	return oeWriteBlob(argv[1], fmt.Sprintf(oeStatDescriptionsHeader, version), "statDescriptionsBlob", scopes)
}

func oracleSkillTextEmit(argv []string) int {
	if len(argv) != 2 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeUsage("usage: skill-text-emit <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	if len(oeObject(dump["effects"])) < 1000 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump carries too few granted effects. Re-run oracle/skill_text.lua.")
	}
	if len(oeArray(dump["goldRespecPrices"])) < 100 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump carries no goldRespecPrices. Re-run oracle/skill_text.lua.")
	}
	return oeWriteBlob(argv[1], fmt.Sprintf(oeSkillTextHeader, oeVersion(dump)), "skillTextBlob",
		map[string]any{"effects": dump["effects"], "gems": dump["gems"], "goldRespecPrices": dump["goldRespecPrices"]})
}

func oeWriteBlob(path, header, name string, blob any) int {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(blob); err != nil {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump does not re-encode: " + err.Error())
	}
	body := header + "const " + name + " = " + strconv.Quote(string(bytes.TrimSpace(buf.Bytes()))) + "\n"
	formatted, err := format.Source([]byte(body))
	if err != nil {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the generated table does not format: " + err.Error())
	}
	return oeWriteGo(path, string(formatted))
}
