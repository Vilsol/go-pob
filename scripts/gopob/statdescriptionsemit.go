const oeStatDescriptionsHeader = `// Code generated by scripts/gopob/statdescriptionsemit.go from go-pob-data %s. DO NOT EDIT.

package raw

import (
	"encoding/json"
	"sync"
)

// The stat description scopes of the game's Metadata/StatDescriptions files (go-pob-data's stat_translations), cut to
// the stats some granted effect can carry and numbered as PoB's export numbers them (Export/Scripts/statdesc.lua),
// read by the gem tooltip (GemTooltip.lua) through calculator's stat describer.
//
// Regenerate with ` + "`task data-regen -- --only stat-descriptions`" + ` after a go-pob-data bump.

// StatDescriptionLimit is one limit of a description variant: Lo / Hi nil for "#"; Not for {"!", n}.
type StatDescriptionLimit struct {
	Lo  *float64 ` + "`json:\"lo,omitempty\"`" + `
	Hi  *float64 ` + "`json:\"hi,omitempty\"`" + `
	Not bool     ` + "`json:\"not,omitempty\"`" + `
}

// StatDescriptionSpec is one index handler of a variant: K applied to stat V (1-based).
type StatDescriptionSpec struct {
	K string ` + "`json:\"k\"`" + `
	V int    ` + "`json:\"v\"`" + `
}

// StatDescriptionVariant is one entry of a description's English list.
type StatDescriptionVariant struct {
	Limit      []StatDescriptionLimit ` + "`json:\"limit\"`" + `
	Text       string                 ` + "`json:\"text\"`" + `
	Specs      []StatDescriptionSpec  ` + "`json:\"specs\"`" + `
	GemQuality bool                   ` + "`json:\"gemQuality,omitempty\"`" + `
}

// StatDescriptor is scope[index]: the stats it reads and its variants (nil for a no_description entry).
type StatDescriptor struct {
	Stats    []string                 ` + "`json:\"stats\"`" + `
	Variants []StatDescriptionVariant ` + "`json:\"variants\"`" + `
}

// StatDescriptionScope is one Data/StatDescriptions module: scope[stat] (Stats) and scope[index] (Descriptors).
type StatDescriptionScope struct {
	Parent      string                    ` + "`json:\"parent\"`" + `
	Stats       map[string]int            ` + "`json:\"stats\"`" + `
	Descriptors map[string]StatDescriptor ` + "`json:\"descriptors\"`" + `
}

var (
	statDescriptionsOnce sync.Once
	statDescriptions     map[string]*StatDescriptionScope
)

func loadStatDescriptions() {
	if err := json.Unmarshal([]byte(statDescriptionsBlob), &statDescriptions); err != nil {
		panic(err)
	}
}

// StatDescriptionScopeByName is LoadModule("Data/StatDescriptions/"..name), nil for an unknown scope.
func StatDescriptionScopeByName(name string) *StatDescriptionScope {
	statDescriptionsOnce.Do(loadStatDescriptions)
	return statDescriptions[name]
}

`

