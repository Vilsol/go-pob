const gemsRenameVar = "pobGemIDtoGameGemIDs"

var gemsRenameRow = regexp.MustCompile(`^` + pySpaceClass + `*"([^"]+)"` + pySpaceClass + `*:` +
	pySpaceClass + `*"([^"]+)"` + pySpaceClass + `*,` + pySpaceClass + `*$`)

var (
	gemsFileDoc      = strings.ReplaceAll(gemsFileDocT, "@", "`")
	gemsStruct       = strings.ReplaceAll(gemsStructT, "@", "`")
	gemsTableDoc     = strings.ReplaceAll(gemsTableDocT, "@", "`")
	gemsVariantsDoc  = strings.ReplaceAll(gemsVariantsDocT, "@", "`")
	gemsEffectMapDoc = strings.ReplaceAll(gemsEffectMapDocT, "@", "`")
)

const gemsFileDocT = `// CODE GENERATED BY @gamedatadump gems@ + @gopob gems-emit@ FROM %s. DO NOT EDIT.
// Regenerate with @task data-regen -- --only gems@.
//
// The //pob: marker above @package@ is a whole-file citation, the right form on a generated
// table: every symbol below is one row of the named Lua file rather than a port of a function.
//
//pob:src/Data/Gems.lua`

const gemsStructT = `// PoBGem is the subset of a src/Data/Gems.lua entry that calcLib.gemIsType reads.
//
// The subset is deliberate: the dumper writes only these fields of each entry and drops
// secondaryEffectName, vaalGem, tagString, defaultLevel, variantId and baseTypeName.
type PoBGem struct {
	// Name is PoB's gem.name. It is not interchangeable with go-pob-data's
	// BaseItemType.Name: PoB drops the " Support" suffix ("Trap", not "Trap Support").
	Name string
	// Tags is PoB's gem.tags -- the gameplay tag set ("spell", "area", "aura", ...).
	Tags map[string]bool
	// GrantedEffectID and SecondaryGrantedEffectID are PoB's gem.grantedEffectId /
	// gem.secondaryGrantedEffectId, through SkillGem.GemVariants: SkillGem.GrantedEffect is 0 on
	// every gem since 3.24. Empty string means the gem declares none.
	GrantedEffectID          string
	SecondaryGrantedEffectID string
	// ReqStr, ReqDex and ReqInt are PoB's gem.reqStr/reqDex/reqInt (SkillGem.Str/Dex/Int).
	ReqStr int
	ReqDex int
	ReqInt int
	// NaturalMaxLevel is PoB's gem.naturalMaxLevel -- the level the UI treats as the gem's
	// natural ceiling, and calcLib.validateGemLevel's second fallback (CalcTools.lua:51).
	// It counts SkillGem.GetLevelProgression(); SkillGem.DefaultLevel() reads the zero
	// GrantedEffect FK and answers Fireball's ladder for every gem. Zero means the gem declares none.
	NaturalMaxLevel int
}`

const gemsTableDocT = `// Gems mirrors PoB's src/Data/Gems.lua, keyed by the gem's metadata id (poe.BaseItemType.ID).
//
// calcLib.gemIsType (src/Modules/CalcTools.lua:99-108) resolves a GemProperty keyword against
// exactly this table. The equivalent field in go-pob-data, poe.SkillGem.Tags, is NOT the same
// data: it indexes Tags.dat rows describing where a gem DROPS, not what it does --
// Fireball's are {mace, helmet, bow, boots, claw, default} -- and Tags.dat carries no
// aoe/spell/support row at all. Hence this port, in the same spirit as SkillBaseFlags.
//
// %d keys come from PoB's own @gameId@ field, which is go-pob-data's BaseItemType.ID --
// PoB declares it exactly where its metadata id and the game id diverge, so this join is EXACT
// rather than a prefix heuristic. %d alternate rows (transfigured/AltX) name a
// gameId their BASE gem already owns, so they cannot live here; they are emitted into
// @GemVariants@ below, keyed by their own granted effect. A further %d
// keys are rewritten. The rewrite table is NOT
// declared here: this file is emitted by parsing builds.%s (builds/parser.go)
// so the PoB-vs-go-pob-data id divergence has exactly one definition.
//
// %d gems, %d distinct tags:
%s`

const gemsVariantsDocT = `// GemVariants holds the src/Data/Gems.lua rows @Gems@ above cannot key: a transfigured gem is
// given its BASE gem's @gameId@ upstream (@SkillGemLancingSteelAltX@ carries
// @gameId = ".../SkillGemLancingSteel"@), so the two rows compete for one slot and the base wins it.
//
// ⚠️ THEY ARE NOT REDUNDANT WITH THE ROW THAT SHADOWS THEM, WHICH IS WHAT THIS TABLE'S ABSENCE
// USED TO ASSERT. Measured on the pinned 3.29 file: of the 213 shadowed rows, 78 carry a DIFFERENT
// tag set from the row shadowing them -- @LancingSteelAltX@ drops @physical@, @ElementalHitAltX@
// drops melee/strike and gains bow/projectile -- and calcLib.gemIsType (CalcTools.lua:99-108)
// resolves every GemProperty keyword against exactly that set. All 213 differ in @name@, which
// CalcPerform.lua:571-572 compares. (@reqStr@/@reqDex@/@reqInt@ and @naturalMaxLevel@ diverge on
// ZERO of the 213, so a consumer of those cannot tell the two rows apart today.)
//
// Keyed by @grantedEffectId@ because that is what PoB matches on: a build XML stores the BASE
// gameId in @gemId@ and the variant in @skillId@, and SkillsTab.lua:445-450 walks
// @data.gemsByGameId[gemId]@ looking for @variant.grantedEffectId == skillId@. Every row in the
// pinned file declares one and they are unique across all 821 rows; a shadowed row without one
// refuses in the emitter, because it would be unreachable by any lookup.
//
// %d rows.`

const gemsEffectMapDocT = `// GemGameIDForGrantedEffectID maps a granted effect id to the game id of the gem that grants it,
// from PoB's own @grantedEffectId@ / @secondaryGrantedEffectId@ beside each gem's @gameId@.
//
// ⚠️ IT EXISTS BECAUSE go-pob-data LEAVES THAT LINK EMPTY. SkillGem.GrantedEffect is 0 on all
// 847 gems and SecondaryGrantedEffect is nil on all 847, so poe's own index
// (@skillGemsByGrantedEffect[obj.GrantedEffect] = obj@) collapses to a SINGLE entry and
// GetSkillGem() resolved for 1 granted effect out of 12816. Same defect as GrantedEffect.StatSet,
// which returned Fireball's stat set for every skill in the game.
//
// Keyed on the granted effect rather than the gem, so unlike @Gems@ above it is NOT shadowed by
// gameId: an alternate-quality row declares its own grantedEffectId and must keep it.
//
// %d entries.
//
// ⚠️ The nolint is gosec G101, which fires on the "ID" in the name against a
// map[string]string and reads it as a hardcoded credential. These are GGG metadata paths from
// PoB's own data file; there is no secret here. Suppressed at the declaration rather than
// repo-wide so the check keeps working everywhere else.
//nolint:gosec // G101 false positive: game metadata ids, not credentials`

func gemsReadRenames(path string) (map[string]string, []string, string) {
	raw, err := os.ReadFile(path) //nolint:gosec // the caller's argument, as in the original
	if err != nil {
		return nil, nil, fmt.Sprintf("cannot read the rename table's source %s: %s",
			path, errnoText(err))
	}
	if !utf8.Valid(raw) {
		return nil, nil, fmt.Sprintf("%s is not valid UTF-8", path)
	}
	src := strings.ReplaceAll(strings.ReplaceAll(string(raw), "\r\n", "\n"), "\r", "\n")

	start := strings.Index(src, gemsRenameVar+" = map[string]string{")
	if start < 0 {
		return nil, nil, fmt.Sprintf("%s declares no `%s = map[string]string{`. It is the single "+
			"definition of the PoB-vs-go-pob-data gem id divergence; if it was renamed or "+
			"moved, point this emitter at it rather than re-declaring the table here.",
			path, gemsRenameVar)
	}
	end := strings.Index(src[start:], "\n}")
	if end < 0 {
		return nil, nil, fmt.Sprintf("%s: %s has no closing brace", path, gemsRenameVar)
	}

	renames := map[string]string{}
	order := []string{}
	lines := pySplitLines(src[start : start+end])
	for _, line := range lines[1:] {
		if pyStrip(line) == "" {
			continue
		}
		m := gemsRenameRow.FindStringSubmatch(line)
		if m == nil {
			return nil, nil, fmt.Sprintf("%s: cannot parse %s row %s",
				path, gemsRenameVar, pyRepr(pyStrip(line)))
		}
		if _, seen := renames[m[1]]; !seen {
			order = append(order, m[1])
		}
		renames[m[1]] = m[2]
	}
	if len(renames) == 0 {
		return nil, nil, fmt.Sprintf("%s: %s is empty", path, gemsRenameVar)
	}
	return renames, order, ""
}

func gemsTagLines(tags []string, perLine int) string {
	out := []string{}
	for i := 0; i < len(tags); i += perLine {
		end := i + perLine
		if end > len(tags) {
			end = len(tags)
		}
		out = append(out, "// "+strings.Join(tags[i:end], ", "))
	}
	return strings.Join(out, "\n")
}

func gemsCheckRows(rows map[string]any, order []string) string {
	for _, key := range order {
		row, ok := rows[key].(map[string]any)
		if !ok {
			return fmt.Sprintf("gem %s is not a JSON object", key)
		}
		id, ok := row["id"].(string)
		if !ok {
			return fmt.Sprintf("gem %s has no 'id' string", key)
		}
		if _, ok := row["name"].(string); !ok {
			return fmt.Sprintf("%s: has no 'name' string", id)
		}
		tags, ok := row["tags"].([]any)
		if !ok {
			return fmt.Sprintf("%s: 'tags' is not a list of strings", id)
		}
		for _, t := range tags {
			if _, ok := t.(string); !ok {
				return fmt.Sprintf("%s: 'tags' is not a list of strings", id)
			}
		}
		loc, present := row["loc"]
		if !present || loc == nil || pyTypeName(loc) == "bool" {
			return fmt.Sprintf("%s: the dumper found no declaring line to cite", id)
		}
		if _, ok := gemsInt(loc); !ok {
			return fmt.Sprintf("%s: declaring line %s is not a number", id, pyRepr(oeStr(loc)))
		}
	}
	return ""
}

func gemsInt(v any) (int, bool) {
	if s, ok := v.(string); ok {
		n, err := strconv.Atoi(pyStrip(s))
		return n, err == nil
	}
	f, ok := oeFloat(v)
	if !ok {
		return 0, false
	}
	return int(f), true
}

func gemsRowLines(key string, row map[string]any) ([]string, string) {
	if !oeTruthy(row["loc"]) {
		s, _ := row["id"].(string)
		return nil, fmt.Sprintf("%s: the dumper found no declaring line to cite", s)
	}
	tagList, _ := row["tags"].([]any)
	tags := make([]string, 0, len(tagList))
	for _, t := range tagList {
		tags = append(tags, fmt.Sprintf("%s: true", oeGoStr(oeStr(t))))
	}
	loc, _ := gemsInt(row["loc"])
	extra := ""
	if oeTruthy(row["grantedEffectId"]) {
		extra += ", GrantedEffectID: " + oeGoStr(oeStr(row["grantedEffectId"]))
	}
	if oeTruthy(row["secondaryGrantedEffectId"]) {
		extra += ", SecondaryGrantedEffectID: " + oeGoStr(oeStr(row["secondaryGrantedEffectId"]))
	}
	for _, fk := range [][2]string{
		{"reqStr", "ReqStr"}, {"reqDex", "ReqDex"}, {"reqInt", "ReqInt"},
		{"naturalMaxLevel", "NaturalMaxLevel"},
	} {
		if oeTruthy(row[fk[0]]) {
			n, _ := gemsInt(row[fk[0]])
			extra += fmt.Sprintf(", %s: %d", fk[1], n)
		}
	}
	return []string{
		fmt.Sprintf("\t// src/Data/Gems.lua:%d", loc),
		fmt.Sprintf("\t%s: {Name: %s, Tags: map[string]bool{%s}%s},",
			oeGoStr(key), oeGoStr(oeStr(row["name"])), strings.Join(tags, ", "), extra),
	}, ""
}

func gemsEmit(args []string) int {
	if len(args) != 3 {
		return oeUsage("usage: gems_emit.py <dump.json> <out.go> <builds/parser.go>")
	}
	dump, body, code := oeLoadDumpBytes(args[0])
	if code != 0 {
		return code
	}
	rowsAny := dump["gems"]

	if !oeTruthy(rowsAny) {
		//go-only: the python named oracle/gems.lua, retired for scripts/gamedatadump gems.
		return oeRefuse("the dump has no gems. Re-run `go run ./scripts/gamedatadump gems`.")
	}
	rows, ok := rowsAny.(map[string]any)
	if !ok {
		return oeRefuse("the dump's 'gems' is not a JSON object")
	}
	order, ok := pyObjectKeyOrder(body, "gems")
	if !ok {
		return oeRefuse("the dump's 'gems' is not a JSON object")
	}

	if reason := gemsCheckRows(rows, order); reason != "" {
		return oeRefuse(reason)
	}
	renames, _, reason := gemsReadRenames(args[2])
	if reason != "" {
		return oeRefuse(reason)
	}

	rowOf := func(k string) map[string]any { return rows[k].(map[string]any) } //nolint:forcetypeassert // gemsCheckRows proved it
	idOf := func(r map[string]any) string { s, _ := r["id"].(string); return s }

	keyed := map[string]map[string]any{}
	keyedOrder := []string{}
	shadowed := []map[string]any{}
	nrenamed, ngameid, nshadowed := 0, 0, 0
	for _, k := range order {
		row := rowOf(k)
		if oeTruthy(row["gameId"]) {
			continue
		}
		id := idOf(row)
		key := id
		if to, ok := renames[id]; ok {
			key = to
		}
		if key != id {
			nrenamed++
		}
		if prev, ok := keyed[key]; ok {
			return oeRefuse(fmt.Sprintf(
				"%s rewrites to %s, which %s already occupies. "+
					"The pinned PoB now declares both ids, so the %s row for it is "+
					"stale -- resolve it there, not here.", id, key, idOf(prev), gemsRenameVar))
		}
		keyed[key] = row
		keyedOrder = append(keyedOrder, key)
	}
	for _, k := range order {
		row := rowOf(k)
		if !oeTruthy(row["gameId"]) {
			continue
		}
		key := oeStr(row["gameId"])
		if _, ok := keyed[key]; ok {
			//go-only: the python emitted no GemVariants table at all -- it DROPPED every shadowed
			if !oeTruthy(row["grantedEffectId"]) {
				return oeRefuse(fmt.Sprintf(
					"%s shares the gameId %s with %s and declares no grantedEffectId, so nothing "+
						"can look it up: it cannot be keyed here and GemVariants has no key for "+
						"it. Model the new shape rather than letting the row vanish.",
					idOf(row), key, idOf(keyed[key])))
			}
			nshadowed++
			shadowed = append(shadowed, row)
			continue
		}
		keyed[key] = row
		keyedOrder = append(keyedOrder, key)
		ngameid++
	}

	sorted := append([]string(nil), keyedOrder...)
	sort.SliceStable(sorted, func(a, b int) bool {
		x, _ := gemsInt(keyed[sorted[a]]["loc"])
		y, _ := gemsInt(keyed[sorted[b]]["loc"])
		return x < y
	})

	body2 := []string{}
	for _, key := range sorted {
		row := keyed[key]
		lines, reason := gemsRowLines(key, row)
		if reason != "" {
			return oeRefuse(reason)
		}
		body2 = append(body2, lines...)
	}

	sort.SliceStable(shadowed, func(a, b int) bool {
		x, _ := gemsInt(shadowed[a]["loc"])
		y, _ := gemsInt(shadowed[b]["loc"])
		return x < y
	})
	variantBody := []string{}
	for _, row := range shadowed {
		lines, reason := gemsRowLines(oeStr(row["grantedEffectId"]), row)
		if reason != "" {
			return oeRefuse(reason)
		}
		variantBody = append(variantBody, lines...)
	}

	allSorted := append([]string(nil), order...)
	sort.SliceStable(allSorted, func(a, b int) bool {
		x, _ := gemsInt(rowOf(allSorted[a])["loc"])
		y, _ := gemsInt(rowOf(allSorted[b])["loc"])
		return x < y
	})
	effectToGame := map[string]string{}
	effectRows := map[string]string{}
	for _, k := range allSorted {
		row := rowOf(k)
		gameID := oeStr(row["gameId"])
		if !oeTruthy(row["gameId"]) {
			gameID = idOf(row)
			if to, ok := renames[gameID]; ok {
				gameID = to
			}
		}
		for _, field := range []string{"grantedEffectId", "secondaryGrantedEffectId"} {
			if !oeTruthy(row[field]) {
				continue
			}
			effect := oeStr(row[field])
			if _, ok := effectToGame[effect]; ok {
				if field == "grantedEffectId" && effectRows[effect] == "grantedEffectId" {
					return oeRefuse(fmt.Sprintf(
						"granted effect %s is claimed as the PRIMARY of both %s=%s and %s; "+
							"the gem link is ambiguous and this emitter cannot pick",
						effect, effectRows[effect], effectToGame[effect], idOf(row)))
				}
				continue
			}
			effectToGame[effect] = gameID
			effectRows[effect] = field
		}
	}
	effectKeys := make([]string, 0, len(effectToGame))
	for k := range effectToGame {
		effectKeys = append(effectKeys, k)
	}
	sort.Strings(effectKeys)
	effectBody := make([]string, 0, len(effectKeys))
	for _, e := range effectKeys {
		effectBody = append(effectBody, fmt.Sprintf("\t%s: %s,", oeGoStr(e), oeGoStr(effectToGame[e])))
	}

	tags := sfeStringList(dump["tagNames"])
	doc := fmt.Sprintf(gemsTableDoc, ngameid, nshadowed, nrenamed, gemsRenameVar,
		len(keyed), len(tags), gemsTagLines(tags, 8))

	lines := make([]string, 0, 18+len(body2)+len(variantBody)+len(effectBody))
	lines = append(lines,
		fmt.Sprintf(gemsFileDoc, oeStr(sfeGet(dump, "pobVersion", "unknown"))),
		"", "package raw", "", gemsStruct, "", doc, "var Gems = map[string]PoBGem{")
	lines = append(lines, body2...)
	lines = append(lines, "}", "", fmt.Sprintf(gemsVariantsDoc, len(shadowed)),
		"var GemVariants = map[string]PoBGem{")
	lines = append(lines, variantBody...)
	lines = append(lines, "}", "", fmt.Sprintf(gemsEffectMapDoc, len(effectBody)),
		"var GemGameIDForGrantedEffectID = map[string]string{")
	lines = append(lines, effectBody...)
	lines = append(lines, "}", "")

	if code := oeWriteGo(args[1], strings.Join(lines, "\n")); code != 0 {
		return code
	}

	unused := []string{}
	for k := range renames {
		if _, ok := rows[k]; !ok {
			unused = append(unused, k)
		}
	}
	sort.Strings(unused)
	fmt.Fprintf(os.Stderr,
		"wrote %s: %d gems, %d shadowed variants, %d distinct tags, %d of %d rename rows applied\n",
		args[1], len(keyed), len(shadowed), len(tags), nrenamed, len(renames))
	if len(unused) > 0 {
		fmt.Fprintf(os.Stderr, "note: %d rename rows match no gem in the pinned Gems.lua: %s\n",
			len(unused), strings.Join(unused, ", "))
	}
	return 0
}
