package main

import (
	"fmt"
	"strconv"
	"strings"
)

const oeFlavourHeader = `// Code generated by scripts/gamedatadump flavour-text + scripts/gopob/flavourtextemit.go from %s. DO NOT EDIT.

package data

import (
	"strings"
	"sync"
)

// Flavour text of PoB's src/Data/FlavourText.lua (the uniques, by name) and of src/Data/Bases/*.lua (an item
// base's flavourText), read by the item tooltip (ItemsTab.lua:4684-4747).
//
// Regenerate with ` + "`task data-regen -- --only flavour-text`" + ` after a PoB pin bump.

// FlavourEntry is one row of data.flavourText: its id and its lines.
type FlavourEntry struct {
	ID   string
	Text []string
}

var (
	flavourOnce       sync.Once
	uniqueFlavourText map[string][]FlavourEntry
	baseFlavourText   map[string][]string
)

// records are split by \x1d, fields by \x1f, lines by \x1e
func loadFlavourText() {
	uniqueFlavourText = map[string][]FlavourEntry{}
	for _, rec := range strings.Split(uniqueFlavourBlob, "\x1d") {
		f := strings.Split(rec, "\x1f")
		uniqueFlavourText[f[0]] = append(uniqueFlavourText[f[0]], FlavourEntry{ID: f[1], Text: strings.Split(f[2], "\x1e")})
	}
	baseFlavourText = map[string][]string{}
	for _, rec := range strings.Split(baseFlavourBlob, "\x1d") {
		f := strings.Split(rec, "\x1f")
		baseFlavourText[f[0]] = strings.Split(f[1], "\x1e")
	}
}

// UniqueFlavourText is flavourLookup (ItemsTab.lua:54-61): a unique name's rows in the module's order.
func UniqueFlavourText(name string) []FlavourEntry {
	flavourOnce.Do(loadFlavourText)
	return uniqueFlavourText[name]
}

// BaseFlavourText is an item base's flavourText, by base name.
func BaseFlavourText(name string) ([]string, bool) {
	flavourOnce.Do(loadFlavourText)
	text, ok := baseFlavourText[name]
	return text, ok
}

`

func oracleFlavourTextEmit(argv []string) int {
	if len(argv) != 2 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeUsage("usage: flavour-text-emit <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	rows := oeArray(dump["uniques"])
	if len(rows) < 1000 {
		return oeRefuse(fmt.Sprintf("the dump carries %d flavour rows; Data/FlavourText.lua did not load. Re-run `go run ./scripts/gamedatadump flavour-text`.", len(rows)))
	}
	const sep = "\x1d\x1e\x1f"
	textLines := func(v any, where string) (string, int) {
		var out []string
		for _, l := range oeArray(v) {
			s, ok := l.(string)
			if !ok || strings.ContainsAny(s, sep) {
				//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
				return "", oeRefuse(where + " has a line that is not plain text")
			}
			out = append(out, s)
		}
		return strings.Join(out, "\x1e"), 0
	}

	var uniques []string
	for i, r := range rows {
		row := oeObject(r)
		name, id := oeStr(row["name"]), oeStr(row["id"])
		if name == "" || id == "" || strings.ContainsAny(name+id, sep) {
			//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
			return oeRefuse(fmt.Sprintf("uniques[%d] has no usable name or id", i))
		}
		text, rc := textLines(row["text"], fmt.Sprintf("uniques[%d] (%s)", i, id))
		if rc != 0 {
			return rc
		}
		uniques = append(uniques, name+"\x1f"+id+"\x1f"+text)
	}

	var bases []string
	baseRows := oeObject(dump["bases"])
	for _, name := range oeSortedKeys(baseRows) {
		text, rc := textLines(baseRows[name], "bases["+name+"]")
		if rc != 0 {
			return rc
		}
		bases = append(bases, name+"\x1f"+text)
	}

	body := fmt.Sprintf(oeFlavourHeader, oeVersion(dump)) +
		"// one record per data.flavourText row, in the module's order\n" +
		"const uniqueFlavourBlob = " + strconv.Quote(strings.Join(uniques, "\x1d")) + "\n\n" +
		"// one record per item base with flavourText, by name\n" +
		"const baseFlavourBlob = " + strconv.Quote(strings.Join(bases, "\x1d")) + "\n"
	return oeWriteGo(argv[1], body)
}
