package main

import (
	"bytes"
	"compress/gzip"
	"encoding/json"
	"fmt"
	"strconv"
)

const oeItemDBHeader = `// Code generated by scripts/gopob/itemdbemit.go from PoB %s. DO NOT EDIT.

package data

// PoB's item databases: every raw unique of data.uniques by its module (src/Modules/Data.lua:1349-1371, the generated
// ones included) and every rare template of data.rares (src/Data/Rares.lua), each with the fields PoB's Item parses
// from it (Main.lua:155-192), which the Go parser is graded against; and the Foulborn map with the lines of the mods
// it names (Data.lua:1373-1375).
//
// Regenerate with ` + "`task data-regen -- --only item-db`" + ` after a PoB pin bump.

`

func oracleItemDBEmit(argv []string) int {
	if len(argv) != 2 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeUsage("usage: item-db-emit <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	if len(oeArray(dump["uniques"])) < 500 || len(oeArray(dump["rares"])) < 50 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse(fmt.Sprintf("the dump carries %d uniques, %d rare templates; Data.lua did not load. Re-run oracle/item_db.lua.",
			len(oeArray(dump["uniques"])), len(oeArray(dump["rares"]))))
	}
	if len(oeObject(dump["foulbornMap"])) < 100 || len(oeObject(dump["foulbornMods"])) < 100 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump carries no Foulborn map or mods; Data.lua did not load. Re-run oracle/item_db.lua.")
	}
	blob, err := json.Marshal(map[string]any{"uniques": dump["uniques"], "rares": dump["rares"], "foulbornMap": dump["foulbornMap"],
		"exclusiveMods": dump["exclusiveMods"], "foulbornMods": dump["foulbornMods"]})
	if err != nil {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump does not re-encode: " + err.Error())
	}
	var gz bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	_, _ = zw.Write(blob)
	if err := zw.Close(); err != nil {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse("the dump does not compress: " + err.Error())
	}
	body := fmt.Sprintf(oeItemDBHeader, oeVersion(dump)) + "const itemDBGz = " + strconv.Quote(gz.String()) + "\n"
	return oeWriteGo(argv[1], body)
}
