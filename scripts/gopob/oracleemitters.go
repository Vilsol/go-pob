// Three of the oracle/ emitter family, ported. Each takes <dump.json> <out.go>, refuses rather
// than writing a plausible empty file, and prints a one-line summary to stderr.
//
// ⚠️ THE HEADER TEXT IS THE PRODUCT, NOT DECORATION. These files ARE the generated Go, so every
// byte of the comment blocks below is output that `task data-regen -- --check` compares against
// what is committed. A reflowed sentence is a diff.

// ------------------------------------------------------------------- skill-minion-uses

const oeMinionUsesHeader = `package raw

// CODE GENERATED BY oracle/skill_minion_uses_emit.py FROM PoB %s. DO NOT EDIT.
// Regenerate with ` + "`task data-regen -- --only minion-uses`" + ` after a PoB pin bump.

// SkillMinionUses and SkillMinionHasItemSet mirror the ` + "`minionUses`" + ` / ` +
	"`minionHasItemSet`" + ` fields of
// PoB's hand-written skill data (src/Data/Skills/*.lua), keyed by granted-effect id, in the same
// spirit as SkillMinionLists.
//
// Neither is extracted game data, which is why go-pob had nothing to key on: ` + "`minionUses`" + ` is a
// literal ` + "`{ [\"Weapon 1\"] = true }`" + ` map written out by hand, and it is the only gate on the two
// blocks that hand a minion its EQUIPMENT — CalcActiveSkill.lua:580-600 (the minion's weaponData)
// and CalcPerform.lua:1158-1176 (every other slot's item and its mods). Without it Animate
// Guardian's minion carries no gear at all.
//
// The set below is COMPLETE BY CONSTRUCTION rather than by assertion: the dumper walks every
// granted effect PoB loads and emits each one that declares the field.
`

const oeItemSetDoc = `
// SkillMinionHasItemSet selects WHERE the slots named by SkillMinionUses are read from — the
// build's own item set rather than the skill's.`

func oracleSkillMinionUsesEmit(argv []string) int {
	if len(argv) != 2 {
		return oeUsage("usage: skill_minion_uses_emit.py <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	uses := oeObject(dump["minionUses"])
	itemSet := oeObject(dump["minionHasItemSet"])

	// REFUSE rather than emit a plausible empty file. An empty SkillMinionUses compiles and
	// silently strips every animated minion of its equipment.
	if !oeTruthy(dump["minionUses"]) {
		return oeRefuse("the dump has no minionUses entries. Re-run oracle/skill_minion_fields.lua.")
	}
	if !oeTruthy(dump["minionHasItemSet"]) {
		return oeRefuse("the dump has no minionHasItemSet entries. PoB has carried three since " +
			"2.18.1; zero means the field was renamed.")
	}

	locs := oeObject(dump["locs"])
	var lines []string
	lines = append(lines, fmt.Sprintf(oeMinionUsesHeader, oeVersion(dump)))

	lines = append(lines, "var SkillMinionUses = map[string]map[string]bool{")
	for _, skillID := range oeSortedKeys(uses) {
		if loc, ok := locs[skillID]; ok && oeTruthy(loc) {
			lines = append(lines, "\t// "+oeStr(loc))
		}
		slots := oeObject(uses[skillID])
		if len(slots) == 1 {
			// The only key, so python's next(iter(slots)) has nothing to be arbitrary about.
			for slot, v := range slots {
				lines = append(lines, fmt.Sprintf("\t%s: {%s: %s},",
					oeGoStr(skillID), oeGoStr(slot), oeGoBool(v)))
			}
			continue
		}
		lines = append(lines, fmt.Sprintf("\t%s: {", oeGoStr(skillID)))
		for _, slot := range oeSortedKeys(slots) {
			lines = append(lines, fmt.Sprintf("\t\t%s: %s,", oeGoStr(slot), oeGoBool(slots[slot])))
		}
		lines = append(lines, "\t},")
	}
	lines = append(lines, "}")

	lines = append(lines, oeItemSetDoc)
	lines = append(lines, "var SkillMinionHasItemSet = map[string]bool{")
	for _, skillID := range oeSortedKeys(itemSet) {
		if loc, ok := locs[skillID]; ok && oeTruthy(loc) {
			lines = append(lines, "\t// "+oeStr(loc))
		}
		lines = append(lines, fmt.Sprintf("\t%s: %s,", oeGoStr(skillID), oeGoBool(itemSet[skillID])))
	}
	lines = append(lines, "}")
	lines = append(lines, "")

	if rc := oeWriteGo(argv[1], strings.Join(lines, "\n")); rc != 0 {
		return rc
	}
	slotCount := 0
	for _, v := range uses {
		slotCount += len(oeObject(v))
	}
	fmt.Fprintf(os.Stderr, "wrote %s: %d minionUses (%d slots), %d minionHasItemSet\n",
		argv[1], len(uses), slotCount, len(itemSet))
	return 0
}

// ------------------------------------------------------------- skill-add-skill-types

const oeAddSkillTypesHeader = `package raw

// CODE GENERATED BY oracle/skill_add_skill_types_emit.py FROM PoB %s. DO NOT EDIT.
// Regenerate with ` + "`task data-regen -- --only skill-add-skill-types`" + ` after a PoB pin bump.
//
// SkillAddSkillTypes is PoB's OWN ` + "`addSkillTypes`" + ` for every SUPPORT gem that declares one
// (src/Data/Skills/*.lua) — the list CalcActiveSkill.lua:101-106 merges into the supported
// skill's skillTypes, in pass 1, before the addFlags pass at :115-120.
//
// Entries here REPLACE poe.GrantedEffects.AddTypes rather than extending it
// (calc_active_skill.go's pass 1 takes the override branch or the go-pob-data branch, never
// both). That is what lets PoB's value win where the two sources disagree, and it is the half
// a merge would get wrong.
//
// ⚠️ IT REPRODUCES PoB'S DUPLICATE-KEY RESOLUTION. A Lua table constructor assigns duplicate
// keys in order, so where a skill declares ` + "`addSkillTypes`" + ` more than once the LAST one wins.
// Nothing special is done for it: the dumper reads the table PoB actually built, so last-wins
// is already applied. The declarations below are scanned from source and their line numbers
// are REGENERATED — an earlier revision of this comment cited act_int.lua:9197 and :9215, and
// under this pin those lines are ` + "`spell = true,`" + ` and ` + "`constantStats = {`" + `. A prose citation of
// a line number is exactly as perishable as a transcribed value.
%s
//
// For SupportBrandSupport that means PoB's Arcanist Brand grants Brand to the spell it
// supports and does NOT grant Triggered — the opposite set from the one the game itself
// declares and go-pob-data carries. We choose PoB's, because PoB is what the oracle grades
// against. The consequence is invisible from our side alone: a supported spell without
// SkillType.Brand gates out every "with Brand skills" mod. On 1139-necromancer-arcanist-brand
// that was node 21389 (Runesmith) ` + "`Speed INC 12`" + `, so CalcOffence.lua:1575's
// Sum("INC", cfg, "Speed", "BrandActivationFrequency") totalled 149 against PoB's 161.
//
// %d supports declare addSkillTypes at this pin.
var SkillAddSkillTypes = map[string][]string{`

func oracleSkillAddSkillTypesEmit(argv []string) int {
	if len(argv) != 2 {
		return oeUsage("usage: skill_add_skill_types_emit.py <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	// REFUSE rather than emit a plausible empty map. An empty table sends EVERY support down
	// the go-pob-data branch — it compiles, it is silent, and it reinstates exactly the
	// Arcanist Brand defect this table exists to fix.
	if !oeTruthy(dump["order"]) || !oeTruthy(dump["entries"]) {
		return oeRefuse("the dump has no supports. Re-run oracle/skill_add_skill_types.lua.")
	}
	order := oeArray(dump["order"])
	entries := oeObject(dump["entries"])

	dupes := oeObject(dump["duplicates"])
	var note []string
	if len(dupes) > 0 {
		note = []string{"//", "// DUPLICATE DECLARATIONS AT THIS PIN (the last of each wins):"}
		for _, sid := range oeSortedKeys(dupes) {
			note = append(note, "//   "+sid)
			for _, hit := range oeArray(dupes[sid]) {
				h := oeObject(hit)
				// ⚠️ `%d`, NOT `%s`. The original formats the line with %d, which TRUNCATES a
				// float toward zero where a string conversion would print the fraction. No dump
				// carries a fractional line number, which is exactly why the difference would
				// never be noticed if it were wrong.
				note = append(note, fmt.Sprintf("//     %s:%s  %s",
					oeStr(h["file"]), oeIntStr(h["line"]), oeStr(h["text"])))
			}
		}
	} else {
		// Not an error — upstream may simply have cleaned it up. But it must be VISIBLE, because
		// the whole reason this table overrides go-pob-data is a duplicate that no longer exists.
		note = []string{"//", "// ⚠️ NO SKILL DECLARES addSkillTypes TWICE AT THIS PIN. The duplicate-key",
			"// resolution described above no longer applies to anything; check whether this",
			"// table still needs to override poe.GrantedEffects.AddTypes at all."}
	}

	lines := []string{fmt.Sprintf(oeAddSkillTypesHeader, oeVersion(dump),
		strings.Join(note, "\n"), len(order))}
	typeCount := 0
	for _, sidAny := range order {
		sid := oeStr(sidAny)
		types := oeArray(entries[sid])
		if !oeTruthy(entries[sid]) {
			// A support declaring an EMPTY addSkillTypes would emit an override that adds
			// nothing while still suppressing go-pob-data's list — strictly worse than no row.
			return oeRefuse(fmt.Sprintf("%s has an empty addSkillTypes; an empty override would "+
				"suppress go-pob-data's list and add nothing in its place.", sid))
		}
		quoted := make([]string, len(types))
		for i, t := range types {
			quoted[i] = oeGoStr(oeStr(t))
		}
		lines = append(lines, fmt.Sprintf("\t%s: {%s},", oeGoStr(sid), strings.Join(quoted, ", ")))
	}
	lines = append(lines, "}")
	lines = append(lines, "")
	lines = append(lines, oeSkillTypeTables(dump)...)

	if rc := oeWriteGo(argv[1], strings.Join(lines, "\n")); rc != 0 {
		return rc
	}
	for _, v := range entries {
		typeCount += len(oeArray(v))
	}
	fmt.Fprintf(os.Stderr, "wrote %s: %d supports, %d type entries\n",
		argv[1], len(order), typeCount)
	return 0
}

// oeSkillTypeTables emits PoB's own skillTypes / excludeSkillTypes / requireSkillTypes, which the
// same dumper (oracle/skill_add_skill_types.lua) writes alongside addSkillTypes. go-pob-data carries
// the GAME's columns, and PoB's differ on a handful of rows, so the calculator prefers these tables
// wherever an id is present. An id that is present with an empty list is authoritative: PoB declares
// nothing there. A dump without these keys (an older dumper) emits empty maps, which leaves every
// lookup on go-pob-data's columns. It does not refuse.
//
// Order: skillTypes is a key set, which the dumper sorts. exclude/require are postfix expressions,
// so their declared order is kept.
//
// This extends the port past the deleted original emitter, whose output ended at SkillAddSkillTypes.
func oeSkillTypeTables(dump map[string]any) []string {
	var out []string
	for _, tbl := range []struct{ key, goName, doc string }{
		{"skillTypes", "SkillTypes", "is PoB's `grantedEffect.skillTypes`, sorted by name"},
		{"excludeSkillTypes", "SkillExcludeSkillTypes", "is PoB's `excludeSkillTypes` for every SUPPORT, in declared (postfix) order"},
		{"requireSkillTypes", "SkillRequireSkillTypes", "is PoB's `requireSkillTypes` for every SUPPORT, in declared (postfix) order"},
	} {
		src := oeObject(dump[tbl.key])
		out = append(out, fmt.Sprintf("// %s %s. %d entries at this pin.", tbl.goName, tbl.doc, len(src)))
		out = append(out, fmt.Sprintf("var %s = map[string][]string{", tbl.goName))
		for _, id := range oeSortedKeys(src) {
			types := oeArray(src[id])
			quoted := make([]string, len(types))
			for i, t := range types {
				quoted[i] = oeGoStr(oeStr(t))
			}
			out = append(out, fmt.Sprintf("\t%s: {%s},", oeGoStr(id), strings.Join(quoted, ", ")))
		}
		out = append(out, "}", "")
	}
	return out
}

// --------------------------------------------------------- skill-has-global-effect

const oeHasGlobalEffectHeader = `package raw

// SkillHasGlobalEffect is PoB's ` + "`grantedEffect.hasGlobalEffect`" + `, set by processMod
// (src/Modules/Data.lua:66-77) for any granted effect whose baseMods, qualityMods, levelMods or
// own statMap carry a GlobalEffect tag. CalcSetup.lua:1140 reads it to decide whether a granted
// effect needs its gem's ` + "`enableGlobal<n>`" + ` box ticked before it becomes an active skill.
//
// CODE GENERATED BY oracle/skill_has_global_effect_emit.py FROM PoB %s. DO NOT EDIT.
// Regenerate with ` + "`task data-regen -- --only skill-has-global-effect`" + ` after a PoB pin bump.
//
// poe.GrantedEffect.HasGlobalEffect() is a hardcoded ` + "`false`" + ` upstream in go-pob-data, so this
// cannot come from the game data and has to come from PoB.
//
// ⚠️ THE PREVIOUS REVISION DERIVED THIS FROM SkillBaseMods AND SkillStatMaps INSTEAD, AND THAT
// IS WHY IT WAS WRONG. The logic mirrored processMod faithfully; its INPUTS were the 2.18.1-era
// tables whose 3.20 regeneration is deliberately held (see scripts/regen_data.py). It answered
// true for %d ids where the pin flags %d — a strict subset, 0 ours-only. A derivation
// inherits the staleness of everything it reads, and nothing downstream could tell the
// difference between a wrong rule and a right rule over old data.
//
// ⚠️ THIS IS THE EAGER SET, WHICH IS THE ONE CalcSetup READS. PoB ALSO sets the flag lazily for
// keys resolved through the global data.skillStatMap metatable (Data.lua:668-679), mutating the
// granted effect at CALCULATION time — so PoB's own answer there depends on which builds the
// process has already calculated. That path is deliberately not mirrored: the eager set is what
// is populated when CalcSetup reads the flag on a fresh run, which is how the oracle was dumped.

var skillHasGlobalEffect = map[string]struct{}{
`

const oeHasGlobalEffectFooter = `}

// SkillHasGlobalEffect reports whether PoB flags this granted effect id.
func SkillHasGlobalEffect(id string) bool {
	_, ok := skillHasGlobalEffect[id]
	return ok
}
`

func oracleSkillHasGlobalEffectEmit(argv []string) int {
	if len(argv) != 2 {
		return oeUsage("usage: skill_has_global_effect_emit.py <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	// REFUSE rather than emit a plausible empty file. An empty set compiles and answers false for
	// every skill, which makes every global-effect gem active without its enableGlobal box — a
	// silent behaviour change in the permissive direction, which is the one nothing catches.
	if !oeTruthy(dump["ids"]) {
		return oeRefuse("the dump carries no flagged ids. Re-run oracle/skill_has_global_effect.lua " +
			"against the pinned PoB.")
	}
	ids, isList := dump["ids"].([]any)
	if !isList {
		return oeRefuse("the dump carries a non-string or empty id; it is malformed")
	}
	for _, i := range ids {
		s, ok := i.(string)
		if !ok || s == "" {
			return oeRefuse("the dump carries a non-string or empty id; it is malformed")
		}
	}

	uniq := map[string]bool{}
	for _, i := range ids {
		uniq[i.(string)] = true
	}
	sorted := make([]string, 0, len(uniq))
	for s := range uniq {
		sorted = append(sorted, s)
	}
	sort.Strings(sorted)

	// ⚠️ 169 IS A LITERAL IN THE ORIGINAL AND STAYS ONE. It is the count the SUPERSEDED derivation
	// produced, quoted so the header can say what was wrong with it; deriving it would be deriving
	// a number that no longer has a source.
	lines := []string{fmt.Sprintf(oeHasGlobalEffectHeader, oeVersion(dump), 169, len(ids))}
	for _, id := range sorted {
		lines = append(lines, fmt.Sprintf("\t%s: {},", oeGoStr(id)))
	}
	lines = append(lines, oeHasGlobalEffectFooter)

	if rc := oeWriteGo(argv[1], strings.Join(lines, "\n")); rc != 0 {
		return rc
	}
	skillCount := "?"
	if v, ok := dump["skillCount"]; ok {
		skillCount = oeStr(v)
	}
	fmt.Fprintf(os.Stderr, "wrote %s: %d flagged granted effects of %s\n",
		argv[1], len(uniq), skillCount)
	return 0
}

// oeVersion is `dump.get("pobVersion", "unknown")`.
func oeVersion(dump map[string]any) string {
	if v, ok := dump["pobVersion"]; ok {
		return oeStr(v)
	}
	return "unknown"
}
