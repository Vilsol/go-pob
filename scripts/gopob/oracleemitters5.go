func sfeWrap(names []string, perLine int) string {
	out := []string{}
	for i := 0; i < len(names); i += perLine {
		end := i + perLine
		if end > len(names) {
			end = len(names)
		}
		out = append(out, "// "+strings.Join(names[i:end], ", "))
	}
	return strings.Join(out, "\n")
}

func sfeFlagTable(rows []map[string]any, column string) ([]string, string) {
	out := []string{}
	for _, row := range rows {
		raw, ok := row[column]
		if !ok || raw == nil {
			continue
		}
		id := oeStr(row["id"])
		flags, isList := raw.([]any)
		if !isList {
			return nil, fmt.Sprintf("%s: %s is not a list of strings", id, column)
		}
		names := make([]string, 0, len(flags))
		for _, f := range flags {
			s, ok := f.(string)
			if !ok {
				return nil, fmt.Sprintf("%s: %s is not a list of strings", id, column)
			}
			names = append(names, oeGoStr(s))
		}
		if !oeTruthy(row["loc"]) {
			return nil, fmt.Sprintf("%s: the dumper found no declaring line to cite", id)
		}
		out = append(out, "\t// "+oeStr(row["loc"]),
			fmt.Sprintf("\t%s: {%s},", oeGoStr(id), strings.Join(names, ", ")))
	}
	return out, ""
}

func skillFlagsEmit(args []string) int {
	if len(args) != 2 {
		return oeUsage("usage: skill_flags_emit.py <dump.json> <out.go>")
	}
	dump, code := oeLoadDump(args[0])
	if code != 0 {
		return code
	}
	skills := dump["skills"]

	if !oeTruthy(skills) {
		return oeRefuse("the dump has no skills. Re-run oracle/skill_flags.lua.")
	}
	skillMap, ok := skills.(map[string]any)
	if !ok {
		return oeRefuse("the dump's 'skills' is not a JSON object")
	}

	rows := make([]map[string]any, 0, len(skillMap))
	for _, k := range oeSortedKeys(skillMap) {
		row, ok := skillMap[k].(map[string]any)
		if !ok {
			return oeRefuse("the dump has a skill with no 'id'")
		}
		if _, ok := row["id"].(string); !ok {
			return oeRefuse("the dump has a skill with no 'id'")
		}
		rows = append(rows, row)
	}
	sort.SliceStable(rows, func(a, b int) bool {
		return oeStr(rows[a]["id"]) < oeStr(rows[b]["id"])
	})

	base, reason := sfeFlagTable(rows, "baseFlags")
	if reason != "" {
		return oeRefuse(reason)
	}
	add, reason := sfeFlagTable(rows, "addFlags")
	if reason != "" {
		return oeRefuse(reason)
	}
	if len(base) == 0 {
		return oeRefuse("no skill carries baseFlags; the dump is structurally wrong")
	}
	if len(add) == 0 {
		return oeRefuse("no skill carries addFlags; the dump is structurally wrong")
	}

	body := []string{}
	var nhidden, nsupport, nfromitem, nfromtree, nadmitted, ncolor, nlegacy, nhide int
	for _, row := range rows {
		name, ok := row["name"].(string)
		if !ok {
			return oeRefuse(fmt.Sprintf("%s: has no 'name' string", oeStr(row["id"])))
		}
		fields := []string{"Name: " + oeGoStr(name)}
		for _, kv := range [][2]string{
			{"hidden", "Hidden"}, {"fromItem", "FromItem"},
			{"fromTree", "FromTree"}, {"support", "Support"},
		} {
			if oeTruthy(row[kv[0]]) {
				fields = append(fields, kv[1]+": true")
			}
		}
		if oeTruthy(row["color"]) {
			if _, ok := oeFloat(row["color"]); !ok || pyTypeName(row["color"]) == "bool" {
				return oeRefuse(fmt.Sprintf("%s: 'color' is not a number", oeStr(row["id"])))
			}
			fields = append(fields, "Color: "+oeIntStr(row["color"]))
			ncolor++
		}
		for _, kv := range [][2]string{{"legacy", "Legacy"}, {"hideFromGemList", "HideFromGemList"}} {
			if oeTruthy(row[kv[0]]) {
				fields = append(fields, kv[1]+": true")
			}
		}
		if plus, ok := row["plusVersionOf"].(string); ok && plus != "" {
			fields = append(fields, "PlusVersionOf: "+oeGoStr(plus))
		}
		nlegacy += sfeBit(row["legacy"])
		nhide += sfeBit(row["hideFromGemList"])
		body = append(body, fmt.Sprintf("\t%s: {%s},", oeGoStr(oeStr(row["id"])),
			strings.Join(fields, ", ")))

		nhidden += sfeBit(row["hidden"])
		nsupport += sfeBit(row["support"])
		nfromitem += sfeBit(row["fromItem"])
		nfromtree += sfeBit(row["fromTree"])
		if !oeTruthy(row["hidden"]) || oeTruthy(row["fromItem"]) || oeTruthy(row["fromTree"]) {
			nadmitted++
		}
	}

	var nbase, nadd, nempty int
	for _, r := range rows {
		if v, ok := r["baseFlags"]; ok && v != nil {
			nbase++
			if a, ok := v.([]any); ok && len(a) == 0 {
				nempty++
			}
		}
		if v, ok := r["addFlags"]; ok && v != nil {
			nadd++
		}
	}

	markers := make([]string, 0, len(sfeSkillFiles))
	for _, f := range sfeSkillFiles {
		markers = append(markers, "//pob:src/Data/Skills/"+f+".lua")
	}

	lines := make([]string, 0, 15+len(base)+len(add)+len(body))
	lines = append(lines,
		fmt.Sprintf(sfeHead, oeStr(sfeGet(dump, "pobVersion", "unknown")),
			strings.Join(markers, "\n")),
		"",
		fmt.Sprintf(sfeBaseDoc, nempty, len(rows), nbase, nadd,
			sfeWrap(sfeStringList(dump["baseFlagNames"]), 9)),
		"var SkillBaseFlags = map[string][]string{",
	)
	lines = append(lines, base...)
	lines = append(lines, "}", "",
		fmt.Sprintf(sfeAddDoc, strings.Join(sfeStringList(dump["addFlagNames"]), ", ")),
		"var SkillAddFlags = map[string][]string{")
	lines = append(lines, add...)
	lines = append(lines, "}", "",
		fmt.Sprintf(sfeSkillDoc, len(rows), len(rows), nhidden, nsupport, nfromitem,
			nfromtree, ncolor, nadmitted, nlegacy, nhide),
		"",
		"var PoBSkills = map[string]PoBSkill{")
	lines = append(lines, body...)
	lines = append(lines, "}", "")

	if code := oeWriteGo(args[1], strings.Join(lines, "\n")); code != 0 {
		return code
	}

	fmt.Fprintf(os.Stderr, "wrote %s: %d skills, %d baseFlags (%d empty), %d addFlags, "+
		"%d hidden, %d support, %d admitted by ModParser.lua:1609\n",
		args[1], len(rows), nbase, nempty, nadd, nhidden, nsupport, nadmitted)
	return 0
}

func sfeBit(v any) int {
	if oeTruthy(v) {
		return 1
	}
	return 0
}

func sfeGet(m map[string]any, key string, def any) any {
	if v, ok := m[key]; ok {
		return v
	}
	return def
}

func sfeStringList(v any) []string {
	a, ok := v.([]any)
	if !ok {
		return nil
	}
	out := make([]string, 0, len(a))
	for _, x := range a {
		out = append(out, oeStr(x))
	}
	return out
}
