package main

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

const oeItemBaseEnchantsHeader = `// Code generated by scripts/gamedatadump item-craft-mods + scripts/gopob/itembaseenchantsemit.go from %s. DO NOT EDIT.

package data

// The bases that carry an enchant (src/Data/Bases/*.lua enchant / enchantModTypes), apart from the crafting
// tables so that parsing an item does not load them.
//
// Regenerate with ` + "`mise run data-regen -- --only item-base-enchants`" + `.

`

func oracleItemBaseEnchantsEmit(argv []string) int {
	if len(argv) != 2 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeUsage("usage: item-base-enchants-emit <dump.json> <out.go>")
	}
	dump, rc := oeLoadDump(argv[0])
	if rc != 0 {
		return rc
	}
	bases := oeObject(dump["bases"])
	names := make([]string, 0)
	for name, b := range bases {
		if e, _ := oeObject(b)["enchant"].(string); e != "" {
			names = append(names, name)
		}
	}
	if len(bases) < 100 || len(names) < 10 {
		//go-only: a new emitter, written in Go from the start; there is no original to share the wording with
		return oeRefuse(fmt.Sprintf("the dump carries %d bases, %d with an enchant; Data.lua did not load. Re-run `go run ./scripts/gamedatadump item-craft-mods`.",
			len(bases), len(names)))
	}
	sort.Strings(names)
	var b strings.Builder
	b.WriteString(fmt.Sprintf(oeItemBaseEnchantsHeader, oeVersion(dump)))
	b.WriteString("var itemBaseEnchants = map[string]ItemBaseEnchant{\n")
	for _, name := range names {
		base := oeObject(bases[name])
		b.WriteString("\t" + strconv.Quote(name) + ": {Enchant: " + strconv.Quote(base["enchant"].(string)) + ", EnchantModTypes: [][]string{")
		for k, types := range oeArray(base["enchantModTypes"]) {
			if k > 0 {
				b.WriteString(", ")
			}
			b.WriteString("{")
			for n, t := range oeArray(types) {
				if n > 0 {
					b.WriteString(", ")
				}
				b.WriteString(strconv.Quote(fmt.Sprint(t)))
			}
			b.WriteString("}")
		}
		b.WriteString("}},\n")
	}
	b.WriteString("}\n")
	return oeWriteGo(argv[1], b.String())
}
