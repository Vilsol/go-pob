const p2mcUsage = "usage: poe2-modcache-emit <dump.json> <out.go> <modcache|quests>"

type p2mcRow struct {
	Line  string          `json:"line"`
	Mods  json.RawMessage `json:"mods"`
	Extra *string         `json:"extra"`
}

func poe2ModCacheEmit(args []string) int {
	if len(args) != 3 {
		return oeUsage(p2mcUsage)
	}
	body, err := os.ReadFile(args[0]) //nolint:gosec // the dump path is the caller's argument
	if err != nil {
		return oeRefuse(fmt.Sprintf("%s is not readable: %s", args[0], errnoText(err)))
	}
	var out string
	switch args[2] {
	case "modcache":
		out, err = p2mcEmit(body)
	case "quests":
		out, err = p2mcQuests(body)
	default:
		return oeUsage(p2mcUsage)
	}
	if err != nil {
		return oeRefuse(fmt.Sprintf("%s: %s", args[0], err))
	}
	return oeWriteGo(args[1], out)
}

func p2mcEmit(body []byte) (string, error) {
	var rows []p2mcRow
	dec := json.NewDecoder(bytes.NewReader(body))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&rows); err != nil {
		return "", fmt.Errorf("does not match the ModCache dump schema: %w", err)
	}
	if len(rows) == 0 {
		return "", fmt.Errorf("holds no rows; the dumper read an empty ModCache")
	}
	sort.Slice(rows, func(i, j int) bool { return rows[i].Line < rows[j].Line })
	for i := 1; i < len(rows); i++ {
		if rows[i].Line == rows[i-1].Line {
			return "", fmt.Errorf("line %q appears twice", rows[i].Line)
		}
	}

	var b strings.Builder
	b.WriteString("// Code generated by scripts/gopob/regendata_poe2_modcache.lua + `gopob poe2-modcache-emit` from the pinned PoB-PoE2. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `task data-regen GAME=poe2 -- --only poe2-modcache`.\n//\n")
	b.WriteString("//pob2:src/Data/ModCache.lua:1\n\npackage poe2\n\n")
	fmt.Fprintf(&b, "// ModCacheRows is src/Data/ModCache.lua, %d lines sorted by line.\n", len(rows))
	b.WriteString("var ModCacheRows = []ModCacheRow{\n")
	for _, r := range rows {
		b.WriteString("\t{Line: " + strconv.Quote(r.Line))
		mods := bytes.TrimSpace(r.Mods)
		if len(mods) > 0 && string(mods) != "null" {
			var compact bytes.Buffer
			if err := json.Compact(&compact, mods); err != nil {
				return "", fmt.Errorf("line %q has unreadable mods: %w", r.Line, err)
			}
			b.WriteString(", Mods: " + strconv.Quote(compact.String()))
		}
		if r.Extra != nil {
			b.WriteString(", Extra: " + strconv.Quote(*r.Extra) + ", HasExtra: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

type p2mcQuest struct {
	Act         float64  `json:"Act"`
	Area        string   `json:"Area"`
	AreaLevel   float64  `json:"AreaLevel"`
	Description string   `json:"Description"`
	Info        string   `json:"Info"`
	Options     []string `json:"Options"`
	QuestPoints *float64 `json:"questPoints"`
	Stat        *string  `json:"Stat"`
	UseConfig   *bool    `json:"useConfig"`
}

func p2mcQuests(body []byte) (string, error) {
	var rows []p2mcQuest
	dec := json.NewDecoder(bytes.NewReader(body))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&rows); err != nil {
		return "", fmt.Errorf("does not match the quest dump schema: %w", err)
	}
	if len(rows) == 0 {
		return "", fmt.Errorf("holds no quests")
	}
	var b strings.Builder
	b.WriteString("// Code generated by scripts/gopob/regendata_poe2_modcache.lua + `gopob poe2-modcache-emit quests` from the pinned PoB-PoE2. DO NOT EDIT.\n")
	b.WriteString("// Regenerate with `task data-regen GAME=poe2 -- --only poe2-quests`.\n//\n")
	b.WriteString("//pob2:src/Data/QuestRewards.lua:1\n\npackage poe2\n\n")
	fmt.Fprintf(&b, "// QuestRewards is data.questRewards, %d quests in PoB's order.\n", len(rows))
	b.WriteString("var QuestRewards = []QuestReward{\n")
	for _, q := range rows {
		if (q.Stat == nil) == (q.Options == nil) {
			return "", fmt.Errorf("quest %s %s %s has both or neither of Stat and Options", q.Description, q.Area, q.Info)
		}
		fmt.Fprintf(&b, "\t{Act: %s, Description: %s, Area: %s, Info: %s, AreaLevel: %s",
			p2eFloat(q.Act), strconv.Quote(q.Description), strconv.Quote(q.Area), strconv.Quote(q.Info), p2eFloat(q.AreaLevel))
		if q.Stat != nil {
			b.WriteString(", Stat: " + strconv.Quote(*q.Stat))
		}
		if q.Options != nil {
			b.WriteString(", Options: " + p2eStrings(q.Options))
		}
		if q.QuestPoints != nil {
			b.WriteString(", QuestPoints: " + p2eFloat(*q.QuestPoints))
		}
		if q.UseConfig != nil && !*q.UseConfig {
			b.WriteString(", NoConfig: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}
