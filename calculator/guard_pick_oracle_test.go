func guardPicksPath(version string) string {
	return filepath.Join("..", "testdata", "oracle-"+version, "guard-picks.tsv")
}

func loadGuardPicks(t *testing.T) map[string]string {
	t.Helper()
	path := guardPicksPath(raw.LatestVersion)
	f, err := os.Open(path)
	if err != nil {
		t.Fatalf("REFUSING: no guard-pick record at %s (%v). Generate it with "+
			"`OPERATOR=true CORPUS=true go test ./calculator/ -run TestGenerateGuardPicks`.", path, err)
	}
	defer f.Close()
	picks := map[string]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		b, pick, ok := strings.Cut(line, "\t")
		if !ok || pick == "" {
			t.Fatalf("REFUSING: malformed guard-pick row %q in %s", line, path)
		}
		picks[b] = pick
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if len(picks) == 0 {
		t.Fatalf("REFUSING: %s has no rows", path)
	}
	return picks
}

// TestGenerateGuardPicks writes guard-picks.tsv from PoB's dumps.
func TestGenerateGuardPicks(t *testing.T) {
	requireOperatorRun(t, "writes testdata/oracle-<version>/guard-picks.tsv from the dumps")
	if os.Getenv("CORPUS") != "true" {
		t.SkipNow()
	}
	dumps := dumpsDirForLoadedData(t)
	corpusDir, names := corpusNamesForLoadedData(t)

	type row struct {
		pick                          string
		multi, noDump, off, ambiguous bool
	}
	rows := make([]row, len(names))
	runConcurrently(len(names), evalWorkers(), func(i int, cache *EnvironmentCache) {
		file, err := os.ReadFile(filepath.Join(corpusDir, names[i]))
		if err != nil {
			return
		}
		build, err := builds.ParseBuild(file)
		if err != nil {
			return
		}
		var env *Environment
		func() {
			defer func() { _ = recover() }()
			env = BuildOutputWithCache(&Calculator{PoB: build}, OutputModeMain, cache)
		}()
		if env == nil {
			return
		}
		var nonVaal []string
		for _, name := range env.guardCandidates {
			if !strings.HasPrefix(name, "Vaal") {
				nonVaal = append(nonVaal, strings.ReplaceAll(name, " ", ""))
			}
		}
		if len(nonVaal) < 2 {
			return
		}
		rows[i].multi = true
		raw, err := os.ReadFile(filepath.Join(dumps, strings.TrimSuffix(names[i], ".xml")+".json"))
		if err != nil {
			rows[i].noDump = true
			return
		}
		var dump struct {
			Conditions map[string]any `json:"conditions"`
		}
		if json.Unmarshal(raw, &dump) != nil {
			rows[i].noDump = true
			return
		}
		alsoBuff := map[string]bool{}
		for _, as := range env.Player.ActiveSkillList {
			for _, buff := range as.BuffList {
				if buff.Type == "Buff" {
					alsoBuff[strings.ReplaceAll(buff.Name, " ", "")] = true
				}
			}
		}
		var hits, clean []string
		for _, n := range nonVaal {
			if v, _ := dump.Conditions["AffectedBy"+n].(bool); v {
				hits = append(hits, n)
				if !alsoBuff[n] {
					clean = append(clean, n)
				}
			}
		}
		switch {
		case len(hits) == 1:
			rows[i].pick = hits[0]
		case len(clean) == 1:
			rows[i].pick = clean[0]
		case len(hits) == 0:
			rows[i].off = true
		default:
			rows[i].ambiguous = true
		}
	})

	var b strings.Builder
	b.WriteString("# build\tnon-Vaal guard the oracle's PoB applied (CalcPerform.lua:3260 pairs() pick)\n")
	b.WriteString("# generated by TestGenerateGuardPicks from the dumps; never hand-edit\n")
	var multi, written, noDump, off, ambiguous int
	var offNames, ambiguousNames []string
	for i, r := range rows {
		if !r.multi {
			continue
		}
		multi++
		switch {
		case r.noDump:
			noDump++
		case r.off:
			off++
			offNames = append(offNames, names[i])
		case r.ambiguous:
			ambiguous++
			ambiguousNames = append(ambiguousNames, names[i])
		default:
			written++
			fmt.Fprintf(&b, "%s\t%s\n", names[i], r.pick)
		}
	}
	if written == 0 {
		t.Fatalf("REFUSING: %d multi-guard builds and no pick recovered — wrong DUMPS?", multi)
	}
	sort.Strings(offNames)
	sort.Strings(ambiguousNames)
	path := guardPicksPath(raw.LatestVersion)
	if err := os.WriteFile(path, []byte(b.String()), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s: %d multi-guard builds, %d picks written, %d without a dump, %d where PoB set "+
		"none of our candidates (NOT pinned): %v, %d ambiguous (NOT pinned): %v", path, multi, written, noDump,
		off, offNames, ambiguous, ambiguousNames)
}

// TestGuardPickTakesTheOracleGuardFirst red-greens the pin on a build with Steelskin and Immortal Call both enabled.
func TestGuardPickTakesTheOracleGuardFirst(t *testing.T) {
	file, err := os.ReadFile("../testdata/corpus-3.29/0502-juggernaut-static-strike-of-gathering-lightning-4.xml")
	if err != nil {
		t.Skipf("fixture build absent: %v", err)
	}
	build, err := builds.ParseBuild(file)
	if err != nil {
		t.Fatal(err)
	}
	affected := func(pick string) map[string]bool {
		cache := NewEnvironmentCache()
		cache.guardPick = pick
		env := BuildOutputWithCache(&Calculator{PoB: build}, OutputModeMain, cache)
		return map[string]bool{
			"ImmortalCall": env.ModDB.Conditions["AffectedByImmortalCall"],
			"Steelskin":    env.ModDB.Conditions["AffectedBySteelskin"],
		}
	}
	if got := affected(""); !got["Steelskin"] || got["ImmortalCall"] {
		t.Fatalf("unpinned walk: want Steelskin only (the fixture's premise), got %v", got)
	}
	if got := affected("ImmortalCall"); !got["ImmortalCall"] || got["Steelskin"] {
		t.Errorf("pinned to Immortal Call: want Immortal Call only, got %v", got)
	}
	if got := affected("MoltenShell"); !got["Steelskin"] || got["ImmortalCall"] {
		t.Errorf("a pick the build does not have must change nothing, got %v", got)
	}
}

// TestGuardPicksSkipBuffTypeNames pins the committed record against the AffectedBy<Name> ambiguity TestGenerateGuardPicks resolves.
func TestGuardPicksSkipBuffTypeNames(t *testing.T) {
	picks := loadGuardPicks(t)
	if got := picks["2063-ladder-wizzardo1337_0658.wizicypangz.xml"]; got != "ImmortalCall" {
		t.Errorf("2063 pinned to %q, want ImmortalCall — regenerate with TestGenerateGuardPicks", got)
	}
}

func corpusEnvPinnedForLoadedData(t *testing.T, file string) *Environment {
	t.Helper()
	if !strings.HasSuffix(file, ".xml") {
		file += ".xml"
	}
	rawXML, err := os.ReadFile(filepath.Join(corpusDirForLoadedData(t), file))
	if err != nil {
		t.Fatalf("REFUSING: %v", err)
	}
	build, err := parsecache.ParseCached(rawXML)
	if err != nil {
		t.Fatalf("REFUSING: %s did not parse: %v", file, err)
	}
	cache := NewEnvironmentCache()
	cache.guardPick = loadGuardPicks(t)[file]
	cache.pairsPicks = loadPairsPicks(t)[file]
	if cache.guardPick != "" {
		t.Logf("guard pick pinned to the oracle's: %s (guard-picks.tsv)", cache.guardPick)
	}
	return BuildOutputWithCache(&Calculator{PoB: build}, OutputModeMain, cache)
}
