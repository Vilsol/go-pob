func pairsPicksPath(version string) string {
	return filepath.Join("..", "testdata", "oracle-"+version, "pairs-picks.tsv")
}

func loadPairsPicks(t *testing.T) map[string]map[string][]string {
	t.Helper()
	path := pairsPicksPath(raw.LatestVersion)
	f, err := os.Open(path)
	if err != nil {
		t.Fatalf("REFUSING: no pairs-pick record at %s (%v). Generate it with "+
			"`OPERATOR=true CORPUS=true go test ./calculator/ -run TestGeneratePairsPicks`.", path, err)
	}
	defer f.Close()
	picks := map[string]map[string][]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if line == "" || strings.HasPrefix(line, "#") {
			continue
		}
		cols := strings.Split(line, "\t")
		if len(cols) != 3 || cols[2] == "" {
			t.Fatalf("REFUSING: malformed pairs-pick row %q in %s", line, path)
		}
		if picks[cols[0]] == nil {
			picks[cols[0]] = map[string][]string{}
		}
		if picks[cols[0]][cols[1]] != nil {
			t.Fatalf("REFUSING: duplicate pairs-pick row %q in %s", line, path)
		}
		picks[cols[0]][cols[1]] = strings.Split(cols[2], ",")
	}
	if err := sc.Err(); err != nil {
		t.Fatal(err)
	}
	if len(picks) == 0 {
		t.Fatalf("REFUSING: %s has no rows", path)
	}
	return picks
}

// TestGeneratePairsPicks writes pairs-picks.tsv from PoB's dumps.
func TestGeneratePairsPicks(t *testing.T) {
	requireOperatorRun(t, "writes testdata/oracle-<version>/pairs-picks.tsv from the dumps")
	if os.Getenv("CORPUS") != "true" {
		t.SkipNow()
	}
	dumps := dumpsDirForLoadedData(t)
	corpusDir, names := corpusNamesForLoadedData(t)

	type row struct {
		curses              []string
		multi, noDump, skip bool
		why                 string
		abyss               map[string]string
		abyssTies           bool
		abyssWhy            []string
	}
	rows := make([]row, len(names))
	runConcurrently(len(names), evalWorkers(), func(i int, cache *EnvironmentCache) {
		file, err := os.ReadFile(filepath.Join(corpusDir, names[i]))
		if err != nil {
			return
		}
		build, err := builds.ParseBuild(file)
		if err != nil {
			return
		}
		var env *Environment
		func() {
			defer func() { _ = recover() }()
			env = BuildOutputWithCache(&Calculator{PoB: build}, OutputModeMain, cache)
		}()
		if env == nil || (len(env.allyCurseCandidates) < 2 && len(env.abyssStatTies) == 0) {
			return
		}
		raw, err := os.ReadFile(filepath.Join(dumps, strings.TrimSuffix(names[i], ".xml")+".json"))
		if err != nil {
			rows[i].noDump = true
			return
		}
		var dump struct {
			CalcsOutput map[string]any          `json:"calcsOutput"`
			ModDB       map[string][]dumpModRow `json:"modDB"`
		}
		if json.Unmarshal(raw, &dump) != nil {
			rows[i].noDump = true
			return
		}
		if len(env.abyssStatTies) > 0 {
			rows[i].abyssTies = true
			rows[i].abyss, rows[i].abyssWhy = abyssPicksFromDump(env.abyssStatTies, dump.ModDB)
		}
		if len(env.allyCurseCandidates) < 2 {
			return
		}
		rows[i].multi = true
		for _, as := range env.Player.ActiveSkillList {
			if as.ActiveEffect != nil && as.ActiveEffect.GrantedEffect != nil &&
				slices.Contains(env.allyCurseCandidates, as.ActiveEffect.GrantedEffect.Name()) {
				rows[i].skip, rows[i].why = true, "player also casts "+as.ActiveEffect.GrantedEffect.Name()
				return
			}
		}
		list, _ := dump.CalcsOutput["CurseList"].(string)
		for _, name := range strings.Split(list, ", ") {
			if slices.Contains(env.allyCurseCandidates, name) && !slices.Contains(rows[i].curses, name) {
				rows[i].curses = append(rows[i].curses, name)
			}
		}
		if len(rows[i].curses) == 0 {
			rows[i].skip, rows[i].why = true, "no ally curse in CurseList"
		}
	})

	var b strings.Builder
	b.WriteString("# build\tkind\tcomma-separated order the oracle's PoB took in a pairs() walk\n")
	b.WriteString("# partyCurses: ally curses in slot order (CurseList), CalcPerform.lua:3138 pairs() over allyPartyCurses\n")
	b.WriteString("# abyssStats: legion node = the stat PassiveSpec.lua:1230 pairs() tried first, read from Tree:<node> mod values\n")
	b.WriteString("# generated by TestGeneratePairsPicks from the dumps; never hand-edit\n")
	var multi, written, noDump, abyssBuilds, abyssWritten int
	var skipped, abyssSkipped []string
	for i, r := range rows {
		if r.abyssTies {
			abyssBuilds++
			if len(r.abyss) > 0 {
				abyssWritten++
				picks := make([]string, 0, len(r.abyss))
				for legionID, key := range r.abyss {
					picks = append(picks, legionID+"="+key)
				}
				sort.Strings(picks)
				fmt.Fprintf(&b, "%s\t%s\t%s\n", names[i], pairsPickAbyssStats, strings.Join(picks, ","))
			}
			for _, why := range r.abyssWhy {
				abyssSkipped = append(abyssSkipped, names[i]+" ("+why+")")
			}
		}
		if !r.multi {
			continue
		}
		multi++
		switch {
		case r.noDump:
			noDump++
		case r.skip:
			skipped = append(skipped, names[i]+" ("+r.why+")")
		default:
			written++
			fmt.Fprintf(&b, "%s\t%s\t%s\n", names[i], pairsPickPartyCurses, strings.Join(r.curses, ","))
		}
	}
	if written == 0 || abyssWritten == 0 {
		t.Fatalf("REFUSING: %d multi-ally-curse builds / %d abyss-tie builds and no pick recovered for one — wrong DUMPS?",
			multi, abyssBuilds)
	}
	sort.Strings(abyssSkipped)
	sort.Strings(skipped)
	path := pairsPicksPath(raw.LatestVersion)
	if err := os.WriteFile(path, []byte(b.String()), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %s: partyCurses %d builds with 2+ ally curses, %d written, %d without a dump, %d NOT pinned: %v",
		path, multi, written, noDump, len(skipped), skipped)
	t.Logf("abyssStats %d builds with a shared-pattern tie, %d written, %d nodes NOT pinned: %v",
		abyssBuilds, abyssWritten, len(abyssSkipped), abyssSkipped)
}

// TestPartyCursePickTakesTheOracleOrder red-greens the pin on 1106: three ally curses, two free slots.
func TestPartyCursePickTakesTheOracleOrder(t *testing.T) {
	file, err := os.ReadFile(filepath.Join(corpusDirForLoadedData(t), "1106-luminary-lightning-tendrils-of-eccentricity.xml"))
	if err != nil {
		t.Skipf("fixture build absent: %v", err)
	}
	build, err := builds.ParseBuild(file)
	if err != nil {
		t.Fatal(err)
	}
	cursed := func(pick []string) map[string]bool {
		cache := NewEnvironmentCache()
		if pick != nil {
			cache.pairsPicks = map[string][]string{pairsPickPartyCurses: pick}
		}
		env := BuildOutputWithCache(&Calculator{PoB: build}, OutputModeMain, cache)
		got := map[string]bool{}
		for _, n := range env.allyCurseCandidates {
			got[n] = countSourcedMods(env.EnemyModDB, "Skill:"+strings.ReplaceAll(n, " ", "")) > 0
		}
		return got
	}
	if got := cursed(nil); !got["Conductivity"] || !got["Elemental Weakness"] || got["Enfeeble"] {
		t.Fatalf("unpinned walk: want Conductivity + Elemental Weakness (sorted names), got %v", got)
	}
	want := loadPairsPicks(t)["1106-luminary-lightning-tendrils-of-eccentricity.xml"][pairsPickPartyCurses]
	if !slices.Equal(want, []string{"Elemental Weakness", "Enfeeble"}) {
		t.Fatalf("1106 pinned to %q, want the oracle's CurseList order — regenerate with TestGeneratePairsPicks", want)
	}
	if got := cursed(want); got["Conductivity"] || !got["Elemental Weakness"] || !got["Enfeeble"] {
		t.Errorf("pinned: want Elemental Weakness + Enfeeble, got %v", got)
	}
	if got := cursed([]string{"Despair"}); !got["Conductivity"] || !got["Elemental Weakness"] || got["Enfeeble"] {
		t.Errorf("a pick the build does not have must change nothing, got %v", got)
	}
}

type dumpModRow struct {
	Source string `json:"source"`
	Value  any    `json:"value"`
}

var dumpListModValue = regexp.MustCompile(`^\{mod=\[(-?[0-9.]+) = `)

func abyssPicksFromDump(ties map[string]abyssStatTie, modDB map[string][]dumpModRow) (map[string]string, []string) {
	values := map[string]map[float64]bool{}
	for _, list := range modDB {
		for _, m := range list {
			nodeID, ok := strings.CutPrefix(m.Source, "Tree:")
			if !ok {
				continue
			}
			nodeID, _, _ = strings.Cut(nodeID, " ")
			var v float64
			switch x := m.Value.(type) {
			case float64:
				v = x
			case string:
				sub := dumpListModValue.FindStringSubmatch(x)
				if sub == nil {
					continue
				}
				f, err := strconv.ParseFloat(sub[1], 64)
				if err != nil {
					continue
				}
				v = f
			default:
				continue
			}
			if values[nodeID] == nil {
				values[nodeID] = map[float64]bool{}
			}
			values[nodeID][v] = true
		}
	}
	picks := map[string]string{}
	var why []string
	nodeIDs := make([]string, 0, len(ties))
	for nodeID := range ties {
		nodeIDs = append(nodeIDs, nodeID)
	}
	sort.Strings(nodeIDs)
	for _, nodeID := range nodeIDs {
		tie := ties[nodeID]
		var hit []string
		seen := map[float64]bool{}
		for key, roll := range tie.rolls {
			if values[nodeID][roll] {
				hit = append(hit, key)
				seen[roll] = true
			}
		}
		sort.Strings(hit)
		switch {
		case len(seen) != 1:
			why = append(why, fmt.Sprintf("node %s %s: %d tied rolls present in the dump", nodeID, tie.legionID, len(seen)))
		case picks[tie.legionID] != "" && !slices.Contains(hit, picks[tie.legionID]):
			why = append(why, fmt.Sprintf("node %s %s: conflicts with another node", nodeID, tie.legionID))
			picks[tie.legionID] = "-"
		case picks[tie.legionID] == "":
			picks[tie.legionID] = hit[0]
		}
	}
	for legionID, key := range picks {
		if key == "-" {
			delete(picks, legionID)
		}
	}
	return picks, why
}

// TestAbyssStatsCrossApplyFirstStat pins PassiveSpec.lua:1229-1232.
func TestAbyssStatsCrossApplyFirstStat(t *testing.T) {
	node := data.LegionNodes["abyss_special_small_attribute35"]
	rolls := tjdata.StatRolls{3, 2}
	if got := substituteAbyssRolls(node, rolls, ""); !slices.Equal(got, []string{
		"Minions have 3% increased Attack Speed", "Minions have 3% increased Cast Speed",
	}) {
		t.Errorf("Rolls order: got %q", got)
	}
	if got := substituteAbyssRolls(node, rolls, "minion_cast_speed_+%"); !slices.Equal(got, []string{
		"Minions have 2% increased Attack Speed", "Minions have 2% increased Cast Speed",
	}) {
		t.Errorf("cast first: got %q", got)
	}
}

// TestAbyssStatPickTakesTheOracleStat red-greens the pin on 8633, whose dump carries 2 on both Tree:6981 speed lines.
func TestAbyssStatPickTakesTheOracleStat(t *testing.T) {
	const b = "8633-ladder-갓시각_4716.CURSE_of_the_PROTEIN.xml"
	file, err := os.ReadFile(filepath.Join(corpusDirForLoadedData(t), b))
	if err != nil {
		t.Skipf("fixture build absent: %v", err)
	}
	build, err := builds.ParseBuild(file)
	if err != nil {
		t.Fatal(err)
	}
	speeds := func(pick []string) []float64 {
		cache := NewEnvironmentCache()
		if pick != nil {
			cache.pairsPicks = map[string][]string{pairsPickAbyssStats: pick}
		}
		env := BuildOutputWithCache(&Calculator{PoB: build}, OutputModeMain, cache)
		var out []float64
		for _, m := range env.ModDB.Mods["MinionModifier"] {
			if mm, ok := m.Value().List().(mod.MinionModifier); ok && mm.Mod != nil &&
				strings.HasPrefix(string(m.GetSource()), "Tree:6981") {
				out = append(out, mm.Mod.Value().Float())
			}
		}
		return out
	}
	if got := speeds(nil); !slices.Equal(got, []float64{3, 3}) {
		t.Fatalf("unpinned: want attack's roll 3 on both lines, got %v", got)
	}
	want := loadPairsPicks(t)[b][pairsPickAbyssStats]
	if !slices.Equal(want, []string{"abyss_special_small_attribute35=minion_cast_speed_+%"}) {
		t.Fatalf("8633 pinned to %q — regenerate with TestGeneratePairsPicks", want)
	}
	if got := speeds(want); !slices.Equal(got, []float64{2, 2}) {
		t.Errorf("pinned: want the dump's 2 on both lines, got %v", got)
	}
	if got := speeds([]string{"abyss_special_small_attribute35=minion_attack_speed_+%"}); !slices.Equal(got, []float64{3, 3}) {
		t.Errorf("planted attack pin: want 3 on both lines, got %v", got)
	}
}
