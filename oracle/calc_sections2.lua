local outPath = arg[1]
local taskLine = arg[2] or "mise run calc-sections-poe2"
assert(outPath, "usage: calc_sections2.lua <out.ts> [task line]")

dofile("HeadlessWrapper.lua")

local json = require("dkjson")

local sections = LoadModule("Modules/CalcSections")

-- a Lua sequence index n is key n-1, as the PoE1 calcSections table keys rows and cells
local function keysOf(t)
	local nums, strs = {}, {}
	for k in pairs(t) do
		if type(k) == "number" then
			nums[#nums + 1] = k
		else
			strs[#strs + 1] = k
		end
	end
	table.sort(nums)
	table.sort(strs)
	return nums, strs
end

local function isScalarList(t)
	local nums, strs = keysOf(t)
	if #strs > 0 or #nums ~= #t then
		return false
	end
	for _, v in ipairs(t) do
		if type(v) == "table" then
			return false
		end
	end
	return true
end

local emit

local function scalar(v)
	if type(v) == "string" then
		return json.quotestring(v)
	elseif type(v) == "number" or type(v) == "boolean" then
		return tostring(v)
	end
	error("unsupported value " .. type(v))
end

local function list(t, indent)
	local parts = {}
	for _, v in ipairs(t) do
		parts[#parts + 1] = emit(v, indent .. "  ")
	end
	if #parts == 0 then
		return "[]"
	end
	return "[\n" .. indent .. "  " .. table.concat(parts, ",\n" .. indent .. "  ") .. "\n" .. indent .. "]"
end

emit = function(v, indent)
	if type(v) ~= "table" then
		return scalar(v)
	end
	if isScalarList(v) and #v > 0 then
		return list(v, indent)
	end
	local nums, strs = keysOf(v)
	local parts = {}
	for _, k in ipairs(strs) do
		if type(v[k]) ~= "function" then
			parts[#parts + 1] = json.quotestring(k) .. ": " .. emit(v[k], indent .. "  ")
		end
	end
	for _, k in ipairs(nums) do
		parts[#parts + 1] = json.quotestring(tostring(k - 1)) .. ": " .. emit(v[k], indent .. "  ")
	end
	if #parts == 0 then
		return "{}"
	end
	return "{\n" .. indent .. "  " .. table.concat(parts, ",\n" .. indent .. "  ") .. "\n" .. indent .. "}"
end

-- CalcsTab.lua builds one CalcSectionControl per entry from { width, id, group, colour, subSection, updateFunc }
local out = {}
for i, s in ipairs(sections) do
	assert(not s[6], s[2] .. " has an update function the generated table cannot carry")
	local subs = {}
	for j, sub in ipairs(s[5]) do
		subs[j] = emit(sub, "      ")
	end
	out[i] = "  [\n    " .. table.concat({
		scalar(s[1]),
		scalar(s[2]),
		scalar(s[3]),
		scalar((s[4]:gsub("^%^x", "#"))),
		"[\n      " .. table.concat(subs, ",\n      ") .. "\n    ]",
	}, ",\n    ") .. "\n  ]"
end

local f = assert(io.open(outPath, "w"))
f:write("// GENERATED by oracle/calc_sections2.lua from the pinned PoB-PoE2's src/Modules/CalcSections.lua\n")
f:write("// (`" .. taskLine .. "`). Do not edit.\n")
f:write("import type { CalcSection2 } from './calc_section_types2';\n\n")
-- the Lua carries a few stray fields (a modType inside a modName list, a label beside a modName), kept as they are
f:write("export const calcSections2 = [\n")
f:write(table.concat(out, ",\n"))
f:write("\n] as unknown as CalcSection2[];\n")
f:close()

io.stderr:write(string.format("calc_sections2: %d sections -> %s\n", #out, outPath))
