local selfPath = arg[0]
local outPath = arg[1]
assert(outPath, "usage: config_options.lua <out.ts>")

local stable = dofile((selfPath:match("^(.*)[/\\]") or ".") .. "/json_stable.lua")

dofile("HeadlessWrapper.lua")

local json = require("dkjson")

local varList = LoadModule("Modules/ConfigOptions")

local copied = {
	"var", "type", "label", "section", "col", "defaultIndex", "defaultState", "defaultPlaceholderState",
	"ifNode", "ifOption", "ifCond", "ifMinionCond", "ifEnemyCond", "ifCondTrue", "ifMult", "ifEnemyMult",
	"ifStat", "ifEnemyStat", "ifTagType", "ifFlag", "ifMod", "ifSkill", "ifSkillFlag", "ifSkillData",
	"includeTransfigured", "implyCond", "implyCondList", "implyMinionCond", "implyEnemyCond",
	"hideIfInvalid", "doNotHighlight", "resizable", "legacy",
}

local out = {}
for i, varData in ipairs(varList) do
	local rec = {}
	for _, k in ipairs(copied) do
		if varData[k] ~= nil then
			rec[k] = varData[k]
		end
	end
	if type(varData.tooltip) == "string" then
		rec.tooltip = varData.tooltip
	elseif varData.tooltip ~= nil then
		rec.dynamicTooltip = true
	end
	if varData.tooltipFunc and varData.list then
		rec.valueTooltips = {}
		for j, entry in ipairs(varData.list) do
			local lines = {}
			local tip = {
				Clear = function() lines = {} end,
				AddLine = function(_, _, text) lines[#lines + 1] = text end,
				AddSeparator = function() lines[#lines + 1] = "" end,
			}
			varData.tooltipFunc(tip, "BODY", j, entry)
			while lines[#lines] == "" do lines[#lines] = nil end
			if #lines > 0 then
				rec.valueTooltips[tostring(entry.val)] = table.concat(lines, "\n")
			end
		end
	elseif varData.tooltipFunc then
		rec.dynamicTooltip = true
	end
	if varData.list then
		rec.list = {}
		for j, entry in ipairs(varData.list) do
			rec.list[j] = { val = entry.val, label = entry.label }
		end
	end
	out[i] = rec
end

local f = assert(io.open(outPath, "w"))
f:write("// GENERATED by oracle/config_options.lua from the pinned PoB's src/Modules/ConfigOptions.lua\n")
f:write("// (`task config-ui-oracles`). Do not edit.\n")
f:write("export default ")
f:write(json.encode(stable(out), { indent = true }))
f:write(" as const;\n")
f:close()

io.stderr:write(string.format("config_options: %d entries -> %s\n", #out, outPath))
